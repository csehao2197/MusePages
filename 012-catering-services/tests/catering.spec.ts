test("responsive navigation and reduced motion without horizontal overflow", async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: "reduce" });
  if(testInfo.project.name==="mobile") {
    await page.getByRole("button", { name: "Open navigation" }).click();
    await expect(page.getByRole("button", { name: "Close navigation" })).toHaveAttribute("aria-expanded","true");
    await page.getByRole("navigation").getByRole("link", { name: "Sample Menus", exact: true }).click();
    await expect(page.getByRole("button", { name: "Open navigation" })).toHaveAttribute("aria-expanded","false");
  } else await expect(page.getByRole("navigation")).toBeVisible();
  await expect(page.locator(".hero-art")).toHaveCSS("animation-name","none");
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.locator("#contact").scrollIntoViewIfNeeded();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.evaluate(() => window.scrollTo(0,0));
  await page.screenshot({ path: `test-results\\${testInfo.project.name}-home.png`, fullPage: true });
});
test("no external requests or console errors, native required fields block submission", async ({ page }) => {
  const errors: string[] = [];
  const external: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("request", r => { if(!r.url().startsWith("http://127.0.0.1:3112")) external.push(r.url()); });
  await page.reload();
  await page.getByRole("button", { name: "Get Your Custom Quote" }).click();
  await expect(page.locator(".confirmation")).toHaveCount(0);
  await expect(page.getByLabel("Full name", { exact: true })).toBeFocused();
  expect(errors).toEqual([]);
  expect(external).toEqual([]);
});
