import { expect, test, type Page } from "@playwright/test";
async function fillInquiry(page: Page) {
  await page.getByLabel("Full name", { exact: true }).fill("Alex Morgan");
  await page.getByLabel("Email", { exact: true }).fill("alex@example.com");
  await page.getByLabel("Phone", { exact: true }).fill("555 234 5678");
  await page.getByLabel("Preferred date", { exact: true }).fill("2030-06-15");
  await page.getByLabel("Venue location", { exact: true }).fill("Fictional Orchard House");
  await page.getByRole("checkbox").check();
}
