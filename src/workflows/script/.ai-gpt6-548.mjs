async function download(url)
{
    const result = await promisify(execFile)("curl.exe", ["--fail", "--location", "--silent", "--show-error", "--max-time", "45", url], { encoding: "buffer", maxBuffer: 30 * 1024 * 1024 });
    return result.stdout;
}

async function fontPackage(name)
{
    const packageName = `@fontsource-variable/${name}`;
    const info = JSON.parse((await download(`https://cdn.jsdelivr.net/npm/${packageName}/package.json`)).toString());
    const url = `https://cdn.jsdelivr.net/npm/${packageName}@${info.version}`;
    const filename = `${name}-latin-wght-normal.woff2`;
    const data = await download(`${url}/files/${filename}`);
    assert.equal(data.subarray(0, 4).toString(), "wOF2");
    const license = await download(`${url}/LICENSE`);
    assert(license.toString().includes("SIL OPEN FONT LICENSE"));
    await fs.writeFile(path.join(folder, "fonts", filename), data);
    await fs.writeFile(path.join(folder, "fonts", `${name}-LICENSE.txt`), license);
    return { package: packageName, version: info.version, url, filename, license: license.toString(), sha256: createHash("sha256").update(data).digest("hex") };
}

