async function exportBytes(directory)
{
    let total = 0;
    for (const entry of await readdir(directory, { withFileTypes: true }))
    {
        const file = path.join(directory, entry.name);
        total += entry.isDirectory() ? await exportBytes(file) : (await stat(file)).size;
    }
    return total;
}

