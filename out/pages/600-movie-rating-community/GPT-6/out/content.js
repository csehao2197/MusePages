export function slugify(value)
{
    return value.toLowerCase().replace(/['’]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function distribution(total, pattern)
{
    const raw = pattern.map((percentage) => total * percentage / 100);
    const counts = raw.map(Math.floor);
    const order = raw.map((number, index) => ({ index, fraction: number - counts[index] }))
        .sort((a, b) => b.fraction - a.fraction || a.index - b.index);
    const remaining = total - counts.reduce((a, b) => a + b, 0);
    for (let i = 0; i < remaining; i++) counts[order[i].index]++;
    return counts;
}

