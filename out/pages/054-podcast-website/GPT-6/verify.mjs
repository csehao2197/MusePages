export async function verify(page,nodeAssert){
  let checks=0;const assert=(condition,message)=>{nodeAssert.ok(condition,message);checks++;};
  await page.setViewportSize({width:1440,height:1000});await page.goto(page.url());
  assert(await page.locator('.episode-row').count()===8,'Eight initial archived concepts');
  await page.locator('#load-more').click();
  assert(await page.locator('.episode-row').count()===16,'Load more reveals additional local concepts');
  await page.locator('[data-filter="AI"]').click();
  assert(await page.locator('.episode-row').count()===2,'AI topic filters real local results');
  await page.locator('#episode-search').fill('zzzz');
  assert(await page.locator('#episode-empty').isVisible(),'Unmatched query has honest empty state');
  await page.locator('#reset-episodes').click();
  await page.locator('#episode-search').fill('<img src=x>');
  assert(await page.locator('#episode-results img').count()===0,'Search query rendered as safe text');
  await page.locator('#clear-search').click();
  await page.locator('#main-play').click();
  await page.waitForFunction(()=>!document.querySelector('#audio').paused&&document.querySelector('#audio').currentTime>.15);
  assert(await page.locator('#audio').evaluate(audio=>Math.abs(audio.duration-16)<.1),'Actual original audio decodes to sixteen seconds');
  assert(await page.locator('#main-play').getAttribute('aria-pressed')==='true','Player starts actual audio');
  assert(await page.locator('#mini-player').isVisible(),'Playing audio opens sticky mini player');
  await page.locator('#mini-play').click();
  assert(await page.locator('#audio').evaluate(audio=>audio.paused),'Mini player pauses the same audio');
  await page.locator('#seek').fill('8');
  assert(await page.locator('#audio').evaluate(audio=>Math.abs(audio.currentTime-8)<.2),'Main seek changes real audio time');
  await page.locator('#mini-seek').fill('4');
  assert(await page.locator('#audio').evaluate(audio=>Math.abs(audio.currentTime-4)<.2),'Mini seek synchronizes real audio time');
  await page.locator('#speed').selectOption('1.5');
  assert(await page.locator('#audio').evaluate(audio=>audio.playbackRate===1.5),'Playback-speed control changes audio rate');
  await page.locator('#volume').fill('20');
  assert(await page.locator('#audio').evaluate(audio=>Math.abs(audio.volume-.2)<.01),'Volume control changes audio volume');
  await page.locator('#seek').fill('15.9');await page.locator('#main-play').click();
  await page.waitForFunction(()=>document.querySelector('#audio').ended);
  assert(await page.locator('#main-play').getAttribute('aria-pressed')==='false','Natural audio completion restores play control');
  await page.locator('#main-play').click();
  await page.waitForFunction(()=>document.querySelector('#audio').currentTime>.1&&document.querySelector('#audio').currentTime<2);
  assert(await page.locator('#audio').evaluate(audio=>!audio.paused),'Finished audio can replay from the beginning');
  await page.locator('#close-player').click();
  assert(!await page.locator('#mini-player').isVisible()&&await page.locator('#audio').evaluate(audio=>audio.paused&&audio.currentTime===0),'Closing mini player stops and resets audio');
  await page.locator('.episode-row [data-play="186"]').click();
  await page.waitForFunction(()=>!document.querySelector('#audio').paused);
  assert((await page.locator('#episode-title').innerText()).includes('Linear'),'Selecting archived demo updates featured episode and mini title');
  await page.locator('#close-player').click();
  await page.locator('#transcript').click();
  assert((await page.locator('#reader-content').innerText()).includes('No interview transcript exists'),'Transcript describes only the original instrumental demo');
  await page.keyboard.press('Escape');
  await page.locator('#share').click();
  const share=await page.locator('.share-url').inputValue();
  assert(share.includes('episode=186')&&!share.includes('054-'),'Episode share URL has public slug and selected episode');
  await page.keyboard.press('Escape');
  await page.goto(share);
  assert((await page.locator('#episode-title').innerText()).includes('Linear')&&await page.locator('#audio').evaluate(audio=>audio.paused),'Shared query restores selected concept without autoplay');
  await page.locator('.platforms [data-platform="Spotify"]').click();
  assert((await page.locator('#reader-content').innerText()).includes('No verified Ship It'),'Platform button does not invent an account');
  await page.keyboard.press('Escape');
  await page.locator('#email').fill('listener@example.com');await page.locator('#signup button').click();
  assert((await page.locator('#signup-status').innerText()).includes('No subscription created'),'Newsletter only previews local signup');
  await page.setViewportSize({width:390,height:900});
  await page.locator('#menu').click();
  assert(await page.locator('#nav').isVisible(),'Mobile navigation opens');
  await page.locator('#nav a[href="#guests"]').click();
  assert(await page.locator('#menu').getAttribute('aria-expanded')==='false','Mobile anchor closes navigation');
  assert(await page.locator('.guest-card').count()===6,'Six clearly proposed guest cards');
  await page.locator('#main-play').click();
  await page.waitForFunction(()=>!document.querySelector('#audio').paused&&document.querySelector('#audio').currentTime>.1);
  assert(await page.locator('#mini-player').isVisible(),'Mobile mini player available');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Playing mini player does not cause mobile overflow');
  await page.locator('#close-player').click();
  await page.goto(page.url().split('?')[0]);
  return checks;
}
