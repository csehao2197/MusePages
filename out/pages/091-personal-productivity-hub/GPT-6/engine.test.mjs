import { test } from "node:test";
import assert from "node:assert/strict";
import { seed, clone, progress, setUnit, logStudy, saveJournal, payBill, prepareNext, receive, setTask, addAssignment, command, parseMoney, nextDue, billStatus, invoiceStatus, validDate } from "./assets/engine.js";
const today = "2026-11-13";
test("unit progress, exact study seconds and per-path journal replacement", () => {
  const state = seed(today);
  assert.equal(progress(state.paths[0]), 46.25);
  setUnit(state, "react", 1, 100);
  assert.equal(progress(state.paths[0]), 55);
  assert.throws(() => setUnit(state, "react", 0, 101));
  assert.throws(() => setUnit(state, "react", 0, 1.5));
  logStudy(state, "react", 65, "timer");
  assert.equal(state.study.at(-1).seconds, 65);
  assert.throws(() => logStudy(state, "missing", 60));
  assert.throws(() => logStudy(state, "react", 0));
  saveJournal(state, "react", "A different perspective. #idea");
  assert.equal(state.journals.length, 1);
  assert.equal(state.journals[0].text, "A different perspective. #idea");
  saveJournal(state, "design", "A new page.");
  assert.equal(state.journals.length, 2);
});
test("bill and partial-income actions conserve cents and link one ledger entry", () => {
  const state = seed(today), opening = state.balance;
  assert.equal(billStatus(state.bills[2], today), "OVERDUE");
  payBill(state, "internet");
  assert.equal(state.balance, opening - 5000);
  assert.equal(state.ledger[0].reference, "internet");
  assert.equal(billStatus(state.bills[0], today), "PAID");
  assert.throws(() => payBill(state, "internet"));
  assert.equal(state.ledger.length, 1);
  receive(state, "website", 12345);
  assert.equal(state.invoices[0].paid, 37345);
  assert.equal(invoiceStatus(state.invoices[0]), "PARTIAL");
  assert.equal(state.balance, opening - 5000 + 12345);
  const before = clone(state);
  assert.throws(() => receive(state, "website", 50000));
  assert.deepEqual(state, before);
  receive(state, "website", 47655);
  assert.equal(invoiceStatus(state.invoices[0]), "PAID");
  state.balance = 1;
  assert.throws(() => payBill(state, "tuition"));
});
test("recurrence clamps month ends and explicitly prevents duplicate occurrences", () => {
  assert.equal(nextDue("2028-01-31", "monthly"), "2028-02-29");
  assert.equal(nextDue("2027-01-31", "monthly"), "2027-02-28");
  assert.equal(nextDue("2026-12-30", "weekly"), "2027-01-06");
  assert.equal(nextDue("2026-12-31", "monthly"), "2027-01-31");
  assert.throws(() => nextDue("2026-02-30", "monthly"));
  const state = seed(today);
  assert.throws(() => prepareNext(state, "internet"));
  payBill(state, "internet");
  prepareNext(state, "internet");
  assert.equal(state.bills.at(-1).due, "2026-12-15");
  assert.equal(state.bills.at(-1).paid, false);
  assert.throws(() => prepareNext(state, "internet"));
  assert.equal(state.bills.length, 4);
});
test("strict dates, cents, assignment validation and independent statuses", () => {
  assert.equal(parseMoney("0.01"), 1);
  assert.equal(parseMoney("123.4"), 12340);
  for (const value of ["0", "-1", "1.001", "1e2", "Infinity", "", " 2", "1000000"]) assert.throws(() => parseMoney(value));
  assert.equal(validDate("2028-02-29"), true);
  assert.equal(validDate("2027-02-29"), false);
  const state = seed(today);
  addAssignment(state, { name: "Explain the state flow", path: "react", due: today });
  assert.equal(state.tasks.at(-1).status, "PENDING");
  assert.throws(() => addAssignment(state, { name: "Explain the state flow", path: "react", due: today }));
  assert.throws(() => addAssignment(state, { name: "New task", path: "react", due: "2026-13-01" }));
  setTask(state, "assignment-react", "DONE");
  assert.equal(state.tasks[0].status, "DONE");
  assert.throws(() => setTask(state, "assignment-react", "COMPLETED"));
});
test("multi-module commands validate and apply atomically, without modifying input", () => {
  const state = seed(today), before = clone(state);
  const result = command(state, "log 2 minutes for React foundations and set React foundations unit 2 to 100% and pay Internet");
  assert.deepEqual(state, before);
  assert.equal(result.state.balance, state.balance - 5000);
  assert.equal(result.state.study.at(-1).seconds, 120);
  assert.equal(result.state.paths[0].units[1].progress, 100);
  assert.equal(result.summary.length, 3);
  assert.throws(() => command(state, "pay Internet and set React foundations unit 99 to 100%"));
  assert.deepEqual(state, before);
  assert.throws(() => command(state, "pay Internet and pay Internet"));
  assert.deepEqual(state, before);
  assert.throws(() => command(state, "please do everything automatically"));
  const incoming = command(state, "receive 125.25 for Website refresh and mark Wireframe review done");
  assert.equal(incoming.state.invoices[0].paid, 37525);
  assert.equal(incoming.state.projects[1].status, "DONE");
});
test("entry limits leave bill and income state untouched on refusal", () => {
  const state = seed(today);
  state.ledger = Array.from({ length: 100 }, () => ({}));
  const before = clone(state);
  assert.throws(() => payBill(state, "internet"));
  assert.throws(() => receive(state, "website", 1));
  assert.deepEqual(state, before);
  state.study = Array.from({ length: 100 }, () => ({}));
  assert.throws(() => logStudy(state, "react", 1));
});
