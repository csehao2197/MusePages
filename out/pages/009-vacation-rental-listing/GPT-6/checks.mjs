import { fileURLToPath } from "node:url";

export async function exercise(page, assert, width) {
  let scenarios = 0;
  const check = (condition, message) => { assert.ok(condition, `${width}px: ${message}`); scenarios++; };
  const equal = (actual, expected, message) => { assert.deepEqual(actual, expected, `${width}px: ${message}`); scenarios++; };
  const text = (selector) => page.locator(selector).first().textContent();
  const mobile = width < 768;
  const close = async (id) => {
    await page.locator(`${id} [data-close]`).first().click();
    await page.waitForFunction((selector) => !document.querySelector(selector).open, id);
  };
  const openBooking = async () => {
    if (mobile && !await page.locator("#booking-dialog").evaluate((node) => node.open)) await page.locator("#mobile-reserve").click();
  };
  const dates = await page.evaluate(() => {
    const now = new Date();
    const today = Date.UTC(now.getFullYear(), now.getMonth(), now.getDate());
    const day = (offset) => new Date(today + offset * 86400000).toISOString().slice(0, 10);
    return { past: day(-1), start: day(1), short: day(3), end: day(8), blocked: day(15), booked: day(12), beforeBooked: day(10) };
  });
  const fillDates = async (start, end) => {
    await page.locator("#check-in").fill(start);
    await page.locator("#check-in").dispatchEvent("change");
    await page.locator("#check-out").fill(end);
    await page.locator("#check-out").dispatchEvent("change");
  };
  await page.evaluate(() => { localStorage.removeItem("staydirect-saved"); localStorage.removeItem("staydirect-currency"); });
  await page.reload({ waitUntil: "networkidle" });
  check((await page.title()).includes("Casa Azul"), "meaningful public title");
  check(!/009-|copilot/i.test(await page.locator("body").innerText()), "public content has no input number or old model name");
  equal(await page.locator(".gallery-photo").count(), 42, "all 42 photographs present");
  equal(await page.locator(".gallery-photo img").evaluateAll((images) => new Set(images.map((image) => image.src)).size), 42, "42 distinct photo resources");
  equal(await page.locator(".gallery-photo:visible").count(), mobile ? 42 : 5, "responsive gallery");
  await page.locator("#show-photos").click();
  equal(await text("#lightbox-count"), "1 / 42", "lightbox starts at first photo");
  await page.keyboard.press("ArrowRight");
  equal(await text("#lightbox-count"), "2 / 42", "lightbox keyboard next");
  if (width === 390) await page.screenshot({ path: fileURLToPath(new URL(".checks/lightbox-390.png", import.meta.url)) });
  await page.keyboard.press("End");
  equal(await text("#lightbox-count"), "42 / 42", "lightbox last photo");
  await page.locator("#photo-next").click();
  equal(await text("#lightbox-count"), "1 / 42", "lightbox wraps");
  await page.locator("#photo-previous").click();
  equal(await text("#lightbox-count"), "42 / 42", "lightbox previous wraps");
  await page.keyboard.press("Escape");
  equal(await page.evaluate(() => document.activeElement.id), "show-photos", "gallery restores opener focus");
  if (mobile) {
    await page.locator("#gallery-track").evaluate((node) => node.scrollTo({ left: node.clientWidth, behavior: "instant" }));
    await page.waitForFunction(() => document.querySelector("#mobile-photo-count").textContent === "2 / 42");
    equal(await text("#mobile-photo-count"), "2 / 42", "mobile native swipe position reflected");
    await page.locator('[data-slide="2"]').click();
    await page.waitForFunction(() => document.querySelector("#mobile-photo-count").textContent === "3 / 42");
    equal(await text("#mobile-photo-count"), "3 / 42", "mobile photo dots navigate");
    await page.locator("#show-photos").click();
    equal(await text("#lightbox-count"), "3 / 42", "lightbox opens current slide");
    await close("#lightbox");
    await page.locator("#menu-button").click();
    check(await page.locator("#mobile-menu").isVisible(), "mobile menu opens");
    await page.locator('#mobile-menu [data-info="Help center"]').click();
    check((await text("#info-content")).includes("three nights"), "mobile help is useful");
    check(!await page.locator("#mobile-menu").isVisible(), "mobile menu closes after selection");
    await close("#info-dialog");
  }
  await page.locator('[data-save="casa"]').click();
  equal(await page.locator('[data-save="casa"]').getAttribute("aria-pressed"), "true", "save home");
  await page.reload({ waitUntil: "networkidle" });
  equal(await page.locator('[data-save="casa"]').getAttribute("aria-pressed"), "true", "saved home persists");
  await page.locator('[data-save="casa"]').click();
  equal(await page.locator('[data-save="casa"]').getAttribute("aria-pressed"), "false", "unsave home");
  await page.locator("#description-toggle").click();
  check(await page.locator(".description-extra").isVisible(), "description expands");
  equal(await page.locator("#description-toggle").getAttribute("aria-expanded"), "true", "description expanded state");
  await page.locator("#description-toggle").click();
  check(!await page.locator(".description-extra").isVisible(), "description collapses");

  await page.locator("#show-amenities").click();
  equal(await page.locator("#all-amenities li").count(), 28, "28 actual amenity entries");
  await page.locator("#amenity-search").fill("wifi");
  equal(await page.locator("#all-amenities li").count(), 1, "amenities filter");
  check((await text("#all-amenities")).includes("150 Mbps"), "amenity result matches query");
  await page.locator("#amenity-search").fill("not-an-amenity");
  equal(await page.locator("#all-amenities li").count(), 0, "amenity empty result");
  check((await text("#amenity-count")).includes("No amenities"), "amenities empty feedback");
  await page.locator("#amenity-search").fill("");
  await page.locator("#amenity-search").focus();
  await page.keyboard.press("Tab");
  equal(await page.evaluate(() => document.activeElement.getAttribute("aria-label")), "Close amenities", "modal last Tab wraps to first control");
  await page.keyboard.press("Shift+Tab");
  equal(await page.evaluate(() => document.activeElement.id), "amenity-search", "modal first reverse Tab wraps to last control");
  await close("#amenities-dialog");
  equal(await page.evaluate(() => document.activeElement.id), "show-amenities", "amenities focus returns");
  equal(await page.locator(".calendar-month").count(), width > 1100 ? 2 : 1, "two desktop months / one compact month");
  const firstMonth = await text(".calendar-month h3");
  check(await page.locator("#previous-month").isDisabled(), "cannot navigate before present month");
  await page.locator("#next-month").click();
  check(await text(".calendar-month h3") !== firstMonth, "calendar next month");
  await page.locator("#previous-month").click();
  equal(await text(".calendar-month h3"), firstMonth, "calendar previous month");
  if (width <= 1100) {
    await page.evaluate(() => {
      const calendar = document.querySelector("#calendars");
      for (const [type, x] of [["touchstart", 250], ["touchend", 100]]) {
        const event = new Event(type, { bubbles: true, cancelable: true });
        Object.defineProperty(event, "changedTouches", { value: [{ clientX: x }] }); calendar.dispatchEvent(event);
      }
    });
    check(await text(".calendar-month h3") !== firstMonth, "compact calendar swipe advances month");
    await page.locator("#previous-month").click();
  }
  check(await page.locator(".date-grid .booked").count() > 0, "booked fixtures present");
  check(await page.locator(".date-grid .booked").first().isDisabled(), "booked date disabled");
  if (await page.locator(".date-grid .past").count()) check(await page.locator(".date-grid .past").first().isDisabled(), "past date disabled");
  await openBooking();
  await page.locator("#reserve").click();
  check((await text("#booking-error")).includes("Choose"), "missing dates rejected");
  await fillDates(dates.start, dates.short);
  check((await text("#booking-error")).includes("3-night"), "minimum stay enforced");
  check(!await page.locator("#price-breakdown").isVisible(), "invalid estimate hidden");
  await fillDates(dates.end, dates.start);
  check((await text("#booking-error")).includes("after"), "reversed dates rejected");
  await fillDates(dates.past, dates.end);
  check((await text("#booking-error")).includes("12 months"), "past date range rejected");
  await fillDates(dates.beforeBooked, dates.blocked);
  check((await text("#booking-error")).includes("booked night"), "range cannot cross unavailable nights");
  await fillDates(dates.start, dates.booked);
  check((await text("#booking-error")).includes("check-out date"), "unavailable checkout rejected");
  await fillDates(dates.start, dates.end);
  equal(await text("#booking-error"), "", "valid seven-night stay");
  const breakdown = await text("#price-breakdown");
  check(breakdown.includes("$2,723"), "seven nightly charges");
  check(breakdown.includes("$150"), "cleaning charge");
  check(breakdown.includes("$459.68"), "IVA computed precisely");
  check(breakdown.includes("$3,332.68"), "seven-night total includes tax cents");
  check(breakdown.includes("$0"), "zero service fee");
  await page.locator("#guest-toggle").click();
  check(await page.locator("#guest-panel").isVisible(), "guest controls expand");
  for (let index = 0; index < 3; index++) await page.locator('[data-guest="children"][data-step="1"]').click();
  await page.locator('[data-guest="infants"][data-step="1"]').click();
  equal(await text("#guest-summary"), "6 guests", "infants count toward capacity");
  for (const kind of ["adults", "children", "infants"]) check(await page.locator(`[data-guest="${kind}"][data-step="1"]`).isDisabled(), `${kind} cannot exceed total capacity`);
  await page.locator('[data-guest="adults"][data-step="-1"]').click();
  check(await page.locator('[data-guest="adults"][data-step="-1"]').isDisabled(), "at least one adult");
  await page.locator('[data-guest="pets"][data-step="1"]').click();
  check(await page.locator('[data-guest="pets"][data-step="1"]').isDisabled(), "one pet maximum");
  check((await text("#price-breakdown")).includes("$350"), "pet fee per night");
  check((await text("#price-breakdown")).includes("$3,738.68"), "pet fee taxed correctly");
  await page.locator("#guests-done").click();
  check(!await page.locator("#guest-panel").isVisible(), "guest controls collapse");
  if (width === 1200 || width === 390) {
    if (mobile) await page.locator("#booking-dialog").evaluate((node) => { node.scrollTop = 0; });
    await page.screenshot({ path: fileURLToPath(new URL(`.checks/booking-${width}.png`, import.meta.url)) });
  }
  await page.locator("#reserve").click();
  check((await text("#confirmation-summary")).includes("$3,738.68"), "reservation preview matches estimate");
  check((await text("#confirmation-dialog")).includes("No dates have been held"), "confirmation honestly identifies demo");
  await page.keyboard.press("Escape");
  equal(await page.evaluate(() => document.activeElement.id), "reserve", "nested confirmation returns to reserve");
  if (mobile) {
    await close("#booking-dialog");
    equal(await page.locator("#booking-card").evaluate((node) => node.parentElement.id), "booking-rail", "mobile booking card restored");
    equal(await page.evaluate(() => document.activeElement.id), "mobile-reserve", "drawer returns focus");
    check((await text("#mobile-date-summary")).includes("7 nights"), "mobile range summary");
    await page.evaluate(async () => {
      document.querySelector("#mobile-reserve").click();
      document.querySelector("#booking-dialog [data-close]").click();
      document.querySelector("#mobile-reserve").click();
      await new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve)));
    });
    equal(await page.locator("#booking-card").evaluate((node) => node.parentElement.id), "booking-mount", "rapid close/reopen preserves active drawer");
    equal(await page.locator("#check-in").inputValue(), dates.start, "drawer reopening retains dates");
    await close("#booking-dialog");
  }
  await page.locator('[data-currency]').last().selectOption("EUR");
  equal(await page.locator('[data-currency]').first().inputValue(), "EUR", "header currency synchronized");
  check((await text('[data-price="389"]')).includes("357.88"), "actual euro conversion");
  await openBooking();
  check((await text("#fx-note")).includes("Not a live"), "fixed FX disclosed");
  check((await text("#price-breakdown")).includes("€3,439.59"), "converted estimate includes pet and taxes");
  if (mobile) await close("#booking-dialog");
  await page.locator('[data-currency]').last().selectOption("GBP");
  equal(await page.locator('[data-currency]').first().inputValue(), "GBP", "GBP selector synchronizes");
  check((await text('[data-price="389"]')).includes("307.31"), "actual pound conversion");
  await page.locator('[data-currency]').last().selectOption("USD");
  await page.locator("#clear-dates").click();
  if (!mobile) check(!await page.locator("#price-breakdown").isVisible(), "clear dates removes estimate");
  check(!(await text("#calendar-status")).includes("Check-in"), "clear dates resets calendar");
  equal(await page.locator(".range-edge").count(), 0, "date highlights cleared");
  let calendarMoves = 0;
  while (!await page.locator(`[data-date="${dates.start}"]`).count() && calendarMoves++ < 2) await page.locator("#next-month").click();
  await page.locator(`[data-date="${dates.start}"]`).click();
  equal(await page.locator("#check-in").inputValue(), dates.start, "calendar sets input check-in");
  if (!await page.locator(`[data-date="${dates.short}"]`).count()) await page.locator("#next-month").click();
  await page.locator(`[data-date="${dates.short}"]`).click();
  check((await text("#calendar-status")).includes("3-night"), "calendar minimum enforced");
  if (!await page.locator(`[data-date="${dates.end}"]`).count()) await page.locator("#next-month").click();
  await page.locator(`[data-date="${dates.end}"]`).click();
  equal(await page.locator("#check-out").inputValue(), dates.end, "calendar sets input check-out");
  check((await text("#calendar-status")).includes("7 nights"), "calendar valid range status");

  await page.locator("#show-reviews").click();
  equal(await page.locator("#all-reviews .review-card").count(), 6, "six actual sample reviews");
  check((await text("#reviews-dialog")).includes("total is a design fixture"), "127 count disclosed");
  await page.locator("#review-search").fill("chef");
  equal(await page.locator("#all-reviews .review-card").count(), 1, "review search");
  check((await text("#all-reviews")).includes("Tom & Linda"), "matching review");
  await page.locator("#review-search").fill("no-such-review");
  check((await text("#review-count")).includes("no matches"), "empty reviews feedback");
  await page.locator("#review-search").fill("");
  await page.locator("#review-sort").selectOption("low");
  check((await page.locator("#all-reviews .review-person h3").first().textContent()).includes("James"), "lowest rating first");
  await page.locator("#review-sort").selectOption("recent");
  check((await page.locator("#all-reviews .review-person h3").first().textContent()).includes("Anna"), "latest review first");
  await close("#reviews-dialog");
  await page.locator("#share-button").click();
  const link = await page.locator("#share-url").inputValue();
  check(link.includes("/pages/vacation-rental-listing/GPT-6/index.html"), "share public number-free listing path");
  await page.evaluate(() => Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText: async () => { throw Error("Clipboard unavailable"); } } }));
  await page.locator("#copy-link").click();
  check((await text("#share-status")).includes("selected"), "clipboard denial has manual fallback");
  equal(await page.locator("#share-url").evaluate((node) => node.selectionEnd - node.selectionStart), link.length, "whole fallback URL selected");
  await page.evaluate(() => Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText: async (value) => { window.__copiedLink = value; } } }));
  await page.locator("#copy-link").click();
  check((await text("#share-status")).includes("copied"), "copy success feedback");
  equal(await page.evaluate(() => window.__copiedLink), link, "copies actual listing link");
  await close("#share-dialog");
  await page.locator('[data-form="message"]').click();
  await page.locator('#demo-form [name="email"]').fill("demo@example.com");
  await page.locator('#demo-form [name="message"]').fill("   ");
  await page.locator("#form-submit").click();
  check(!await page.locator('#demo-form [name="message"]').evaluate((node) => node.validity.valid), "whitespace message rejected");
  await page.locator('#demo-form [name="message"]').fill("A sample question about check-in.");
  await page.locator("#form-submit").click();
  check((await text("#form-status")).includes("Nothing was sent or stored"), "message submission honest and local");
  equal(await page.locator('#demo-form [name="email"]').inputValue(), "", "personal inputs cleared");
  await close("#form-dialog");
  await page.locator('[data-info="Report a concern"]').click();
  await page.locator('#demo-form [name="reason"]').selectOption("Safety concern");
  await page.locator('#demo-form [name="details"]').fill("Sample concern.");
  await page.locator("#form-submit").click();
  check((await text("#form-status")).includes("no account or report"), "report remains demo");
  await close("#form-dialog");
  await page.locator('[data-info="How it works"]').last().click();
  check((await text("#info-content")).includes("does not create reservations"), "footer destination meaningful");
  await close("#info-dialog");
  await page.locator('[data-stay="treehouse"]').first().click();
  check((await text("#info-content")).includes("$189"), "similar listing real preview");
  check((await text("#info-content")).includes("cannot be booked"), "similar listing limitation");
  await close("#info-dialog");
  await page.locator('[data-save="treehouse"]').click();
  equal(await page.locator('[data-save="treehouse"]').getAttribute("aria-pressed"), "true", "similar heart works");
  await page.locator('[data-info="Privacy"]').click();
  await page.locator("#clear-saved").click();
  equal(await page.evaluate(() => localStorage.getItem("staydirect-saved")), null, "privacy clear removes saved data");
  await close("#info-dialog");
  await page.locator('[data-zoom="1"]').click();
  check(Number(await page.locator("#area-map").getAttribute("data-zoom")) > 1, "illustrated map zooms");
  await page.locator('[data-zoom="-1"]').click();
  equal(await page.locator("#area-map").getAttribute("data-zoom"), "1", "map zoom resets");
  const storedValues = await page.evaluate(() => Object.values(localStorage).join(" "));
  check(!storedValues.includes("demo@example.com") && !storedValues.includes("question about"), "no personal information persisted");
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "no page horizontal overflow");
  const smallTargets = await page.locator(".quick-actions button:visible, .mobile-photo-dots button:visible, .header-book:visible, .date-grid button:visible, .map-zoom button:visible").evaluateAll((nodes) => nodes.filter((node) => {
    const box = node.getBoundingClientRect(); return box.width < 43.9 || box.height < 43.9;
  }).map((node) => node.outerHTML.slice(0, 100)));
  equal(smallTargets, [], "key interactive targets at least 44px");
  await page.evaluate(async () => {
    for (const image of document.images) image.loading = "eager";
    await Promise.all([...document.images].map((image) => image.decode()));
    await document.fonts.ready;
  });
  equal(await page.locator("img").evaluateAll((images) => images.filter((image) => !image.complete || image.naturalWidth === 0).length), 0, "all local images decode");
  check(await page.evaluate(() => document.fonts.check('16px "DM Sans"') && document.fonts.check("16px Inter")), "local fonts ready");
  const blockedContext = await page.context().browser().newContext({ viewport: { width, height: 900 } });
  try {
    await blockedContext.addInitScript(() => {
      Object.defineProperty(window, "localStorage", { get() { throw new DOMException("Storage denied", "SecurityError"); } });
    });
    const deniedPage = await blockedContext.newPage();
    const errors = [];
    deniedPage.on("pageerror", (error) => errors.push(error.message));
    await deniedPage.goto(page.url(), { waitUntil: "networkidle" });
    await deniedPage.locator('[data-save="casa"]').click();
    equal(await deniedPage.locator('[data-save="casa"]').getAttribute("aria-pressed"), "true", "storage-denied save works in memory");
    check((await deniedPage.locator("#toast").textContent()).includes("this tab only"), "storage denial disclosed");
    equal(errors, [], "storage denial does not crash");
  } finally { await blockedContext.close(); }
  return scenarios;
}
