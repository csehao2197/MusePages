  const page=await context.newPage();page.setDefaultTimeout(7000);
  page.on('pageerror',error=>errors.push(String(error)));
  page.on('response',response=>{if(response.status()>=400)errors.push(`${response.status()} ${response.url()}`);});
  page.on('request',request=>requests.push({url:request.url(),method:request.method()}));
  const response=await page.goto(server.url,{waitUntil:'networkidle',timeout:20000});
  check(response.status()===200,'Nested mount responds');
  check(new URL(server.url).pathname.includes('/pages/transformation-story-gallery/GPT-6/'),'True numberless nested mount');
  await page.evaluate(async()=>{await document.fonts.ready;await Promise.all([...document.images].filter(image=>image.getAttribute('src')).map(image=>image.decode()));});
  check(await page.evaluate(()=>document.fonts.check('16px Inter')&&document.fonts.check('700 50px Barlow')),'Local fonts ready');
  check(await page.locator('.story-card').count()===6,'All stories rendered');
  const range=page.getByRole('slider',{name:'Featured before and after comparison'});
  await range.focus();await range.press('ArrowRight');
  check(await range.inputValue()==='51','Comparison keyboard control');
  await page.locator('[name=goal]').selectOption('Muscle Gain');
  check(await page.locator('.story-card').count()===1,'Goal filter');
  check((await page.locator('.card-title').textContent()).includes('Marcus'),'Correct goal result');
  await page.getByRole('button',{name:'Reset filters',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.story-card').length===6);
  await page.locator('[name=age]').selectOption('60+');
  check((await page.locator('.card-title').textContent()).includes('Diane'),'Age filter');
  await page.locator('[name=gender]').selectOption('Male');
  check(await page.locator('#no-results').isVisible(),'Combined filters empty state');
  await page.getByRole('button',{name:'Show all stories'}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.story-card').length===6);
  await page.locator('[name=time]').selectOption('3');
  check((await page.locator('.card-title').textContent()).includes('Elena'),'Time filter');
  await page.locator('[name=program]').selectOption('Group Classes');
  check(await page.locator('.story-card').count()===1,'Program combined filter');
  await page.locator('#filters').evaluate(form=>form.reset());
  await page.waitForFunction(()=>document.querySelectorAll('.story-card').length===6);
  await page.getByRole('searchbox').fill('hiking');
  check(await page.locator('.story-card').count()===0,'Search empty case');
  await page.getByRole('searchbox').fill('James');
  check(await page.locator('.story-card').count()===1,'Name search');
  await page.getByRole('searchbox').fill('');
  await page.locator('#sort').selectOption('popular');
  check((await page.locator('.card-title').first().textContent()).includes('Sarah'),'Popularity order');
  await page.locator('#sort').selectOption('change');
  check((await page.locator('.card-title').first().textContent()).includes('Sarah'),'Largest example change order');
  const toggle=page.locator('[data-toggle=sarah]');await toggle.click();
  check(await toggle.getAttribute('aria-pressed')==='true','Photo toggle');
  await page.locator('[data-story=sarah]').last().click();
  check(await page.getByRole('dialog',{name:'Sarah Mitchell’s next chapter'}).isVisible(),'Detailed story dialog');
  check(await page.locator('#story-dialog .progress-photos img').count()===3,'Detailed progress views');
  await page.locator('#story-dialog input[type=range]').focus();await page.locator('#story-dialog input[type=range]').press('ArrowLeft');
  check(await page.locator('#story-dialog input[type=range]').inputValue()==='49','Detailed comparison keyboard accessible');
  await page.keyboard.press('Escape');
  check(!await page.locator('#story-dialog').isVisible(),'Native Escape closes story');
  await page.locator('[data-program-filter="Nutrition Coaching"]').click();
  check(await page.locator('.story-card').count()===2,'Program results link filters gallery');
  await page.locator('#next').click();
  check(await page.locator('#compare-name').textContent()==='Marcus T.','Comparison next');
  await page.locator('#previous').click();
  check(await page.locator('#compare-name').textContent()==='Sarah M.','Comparison previous');
  await page.locator('#autoplay').click();
  await page.waitForFunction(()=>document.querySelector('#comparison-range').value!=='50');
  check(await page.locator('#autoplay').getAttribute('aria-pressed')==='true','Auto-play running');
  await page.locator('#autoplay').click();
  check(await page.locator('#autoplay').getAttribute('aria-pressed')==='false','Auto-play pause');
  await page.locator('#share-story').click();
