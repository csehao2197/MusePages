export async function verify(page, assert) {
  let checks = 0;
  assert.equal(await page.locator(".alumni-card").count(), 4); checks++;
  await page.locator("#search").fill("Stripe");
  assert.equal(await page.locator(".alumni-card").count(), 1);
  assert.match(await page.locator(".alumni-card").textContent(), /Aisha/); checks += 2;
  await page.locator("#year").selectOption("2005");
  assert.equal(await page.locator(".no-results").isVisible(), true); checks++;
  await page.locator("#reset").click();
  await page.locator("#location").selectOption("Tokyo");
  assert.match(await page.locator(".alumni-card").textContent(), /Tom/); checks++;
  await page.locator("#reset").click();
  await page.locator("#chapter").selectOption("Boston");
  assert.match(await page.locator(".alumni-card").textContent(), /Elena/); checks++;
  await page.locator("#reset").click();
  await page.locator("[data-connect='0']").click();
  await page.locator("#name").fill("<b>Taylor</b>");
  await page.locator("#form-email").fill("alumni@example.com");
  await page.locator("#note").fill("Hello from the class of 2012.");
  await page.locator("#local-form button").click();
  assert.match(await page.locator("#receipt").textContent(), /<b>Taylor<\/b>/);
  assert.equal(await page.locator("#receipt b").count(), 0); checks += 2;
  await page.keyboard.press("Escape");
  await page.locator("[data-event='1']").first().click();
  assert.match(await page.locator("#dialog-content").textContent(), /Registration and live joining are closed/); checks++;
  const [download] = await Promise.all([page.waitForEvent("download"), page.locator("#download-event").click()]);
  assert.equal(download.suggestedFilename(), "crestfield-archived-event.ics"); checks++;
  await page.keyboard.press("Escape");
  assert.match(await page.locator(".event-row").nth(1).textContent(), /Friday/); checks++;
  assert.match(await page.locator(".event-row").nth(2).textContent(), /Thursday/); checks++;
  await page.locator("[data-story='0']").first().click();
  assert.match(await page.locator("#dialog-content").textContent(), /Fictional story/); checks++;
  await page.keyboard.press("Escape");
  await page.locator("[data-campaign='STEM Scholarship Fund']").click();
  await page.locator("#amount").fill("125.50");
  await page.locator("#frequency").selectOption({ label: "Monthly gift" });
  await page.locator("#gift-form button").click();
  assert.match(await page.locator("#gift-receipt").textContent(), /\$125.50/); checks++;
  await page.keyboard.press("Escape");
  await page.locator("[data-chapter='2']").click();
  assert.match(await page.locator("#dialog-title").textContent(), /London/); checks++;
  await page.keyboard.press("Escape");
  await page.locator(".benefit-grid summary").first().click();
  assert.equal(await page.locator(".benefit-grid details").first().getAttribute("open"), ""); checks++;
  await page.locator("#email").fill("alumni@example.com");
  await page.locator("#signup-form button").click();
  assert.match(await page.locator("#signup-status").textContent(), /No account/); checks++;
  assert.equal(await page.locator("img").evaluateAll((imgs) => imgs.every((img) => img.complete && img.naturalWidth > 0)), true); checks++;
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator("#filter-toggle").click();
  assert.equal(await page.locator("#filters").isVisible(), true); checks++;
  await page.locator("#menu").click();
  assert.equal(await page.locator("header nav").isVisible(), true); checks++;
  await page.locator("header nav a[href='#directory']").click();
  assert.equal(await page.locator("#menu").getAttribute("aria-expanded"), "false"); checks++;
  assert.equal(await page.locator(".mobile-join").isVisible(), true); checks++;
  return checks;
}
