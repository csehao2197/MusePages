export async function verify(page,nodeAssert){
  let checks=0;const assert=(condition,message)=>{nodeAssert.ok(condition,message);checks++;};
  await page.setViewportSize({width:1440,height:1000});await page.goto(page.url());
  assert(await page.locator('.story').count()===5,'Five asymmetric editorial stories');
  assert(await page.locator('.gallery-item').count()===9,'Nine selected gallery frames');
  await page.locator('.hero [data-read="trecime"]').click();
  assert((await page.locator('#reader-content').innerText()).includes('not a verified hike'),'Hero opens honest original story preview');
  await page.keyboard.press('Escape');
  await page.locator('#stories').scrollIntoViewIfNeeded();
  await page.waitForFunction(()=>document.querySelector('#header').classList.contains('solid'));
  assert(await page.locator('#header').evaluate(header=>header.classList.contains('solid')),'Scrolled header gains legible light background');
  const before=await page.locator('#destination-grid').evaluate(element=>element.scrollLeft);
  await page.locator('#dest-next').click();
  await page.waitForFunction(()=>document.querySelector('#destination-grid').scrollLeft>0);
  assert(await page.locator('#destination-grid').evaluate(element=>element.scrollLeft)>before,'Desktop destination arrow scrolls cards');
  await page.locator('[data-destination="Iceland"]').first().click();
  assert(await page.locator('#reader-content [data-read="iceland"]').count()===1,'Destination shows actual implemented local story');
  await page.keyboard.press('Escape');
  await page.locator('[data-destination="Norway"]').click();
  assert((await page.locator('#reader-content').innerText()).includes('No local story'),'Unavailable destination archive shows honest empty state');
  await page.keyboard.press('Escape');
  await page.locator('.gallery-item').first().click();
  assert(await page.locator('#lightbox').isVisible(),'Gallery opens image lightbox');
  assert((await page.locator('#lightbox-meta').innerText()).includes('not embedded EXIF'),'Capture settings clearly identified as sample metadata');
  await page.keyboard.press('ArrowRight');
  assert((await page.locator('#lightbox-index').innerText()).includes('02 / 9'),'Keyboard advances gallery');
  await page.locator('#lightbox-prev').click();
  await page.locator('#lightbox-prev').click();
  assert((await page.locator('#lightbox-index').innerText()).includes('09 / 9'),'Gallery wraps backward to final frame');
  await page.keyboard.press('Escape');
  await page.locator('#compare-range').fill('80');
  assert(await page.locator('#compare-output').innerText()==='80% flat preview','Editing slider updates reveal label');
  assert(await page.locator('.comparison').evaluate(element=>element.style.getPropertyValue('--split'))==='80%','Editing slider changes image clipping');
  await page.locator('#compare-range').focus();await page.keyboard.press('ArrowLeft');
  assert(await page.locator('#compare-range').inputValue()==='79','Editing slider supports keyboard adjustments');
  await page.locator('[data-gear="filters"]').click();
  assert((await page.locator('#reader-content').innerText()).includes('magnetic-system assertion has not been verified'),'Gear review avoids repeating unverified product mechanism');
  await page.keyboard.press('Escape');
  await page.locator('.print-card [data-print="0"]').last().click();
  await page.locator('[name="finish"]').selectOption('60');
  assert(await page.locator('.print-estimate').innerText()==='Illustrative estimate: $249','Print framing updates local estimate correctly');
  await page.locator('.print-options .gold-button').click();
  assert((await page.locator('.print-confirm').innerText()).includes('No order created'),'Print preview never claims an order');
  await page.keyboard.press('Escape');
  await page.locator('#open-search').click();
  await page.locator('#search').fill('Lightroom');await page.locator('#search-form button').click();
  assert(await page.locator('#reader-content [data-read="edit"]').count()===1,'Search discovers editing preview');
  await page.keyboard.press('Escape');
  await page.locator('#email').fill('reader@example.com');await page.locator('#signup button').click();
  assert((await page.locator('#signup-status').innerText()).includes('No subscription created'),'Newsletter only previews local signup');
  await page.setViewportSize({width:390,height:900});
  await page.locator('#open-menu').click();
  assert(await page.locator('#mobile-nav').isVisible(),'Mobile full-screen menu opens');
  await page.locator('#mobile-nav a[href="#destinations"]').click();
  assert(!await page.locator('#mobile-nav').isVisible(),'Mobile navigation closes after selection');
  await page.locator('#open-menu').click();await page.locator('#mobile-search').click();
  assert(await page.locator('#search-dialog').isVisible()&&!await page.locator('#mobile-nav').isVisible(),'Mobile search replaces menu dialog safely');
  await page.locator('#search').fill('<img src=x>');await page.locator('#search-form button').click();
  assert(await page.locator('#reader-content h2 img').count()===0,'Search title safely renders user text');
  await page.keyboard.press('Escape');
  await page.locator('#compare-range').fill('25');
  assert(await page.locator('#compare-output').innerText()==='25% flat preview','Mobile editing control updates');
  await page.evaluate(async()=>{for(const image of document.images)image.loading='eager';await Promise.all([...document.images].map(image=>image.decode().catch(()=>{})));});
  assert(await page.locator('img').evaluateAll(images=>images.filter(image=>image.getAttribute('src')).every(image=>image.complete&&image.naturalWidth>0)),'All bundled photographs decode');
  await page.locator('#compare-range').fill('50');
  await page.evaluate(()=>window.scrollTo(0,0));return checks;
}
