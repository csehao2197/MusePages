export async function exercise(page, assert) {
  assert.equal(await page.locator(".stay-card").count(), 4);
  await page.getByRole("checkbox", { name: "Shinjuku", exact: false }).check();
  assert.equal(await page.locator(".stay-card").count(), 2);
  await page.getByRole("button", { name: "Remove Shinjuku filter", exact: true }).click();
  await page.getByLabel("Sort hotels", { exact: true }).selectOption("low");
  assert.match(await page.locator(".stay-name").first().innerText(), /Capsule/);
  await page.getByRole("button", { name: "Grid view", exact: true }).click();
  assert.ok(await page.locator("#hotels").evaluate(e=>e.classList.contains("grid-view")));
  await page.getByRole("button", { name: "List view", exact: true }).click();
  const photo=await page.locator(".stay-image img").first().getAttribute("src");
  await page.getByRole("button", { name: "Next photo of Capsule Hotel Anshin Oyado", exact: true }).click();
  assert.notEqual(await page.locator(".stay-image img").first().getAttribute("src"),photo);
  await page.getByRole("button", { name: "Save Park Hyatt Tokyo", exact: true }).click();
  await page.getByRole("button", { name: "Show saved hotels", exact: true }).click();
  assert.equal(await page.locator(".stay-card").count(),1);
  await page.getByRole("button", { name: "Book Now" }).click();
  await page.locator('[data-room="2"]').click();
  assert.equal(await page.locator("#selected-room").innerText(), "Suite");
  await page.getByRole("button", { name: "Reserve Now" }).click();
  assert.match(await page.locator("#reservation-status").innerText(), /no booking was made/);
  await page.getByRole("button", { name: "Close dialog" }).click();
  assert.ok(await page.locator("#recent").isVisible());
  await page.getByRole("button", { name: "Show Map", exact: true }).click();
  await page.locator('[data-marker="1"]').click();
  assert.match(await page.locator("#map-mini").innerText(), /MUJI/);
  await page.getByRole("button", { name: "Zoom in", exact: true }).click();
  assert.match(await page.locator("#map-layer").getAttribute("style"), /1.2/);
  await page.getByRole("button", { name: "Search this area", exact: true }).click();
  assert.match(await page.locator("#map-status").innerText(), /No live map/);
  await page.getByRole("button", { name: "Close dialog" }).click();
  await page.getByRole("button", { name: "Show saved hotels", exact: true }).click();
  await page.getByLabel("Check-out", { exact: true }).fill("2026-04-22");
  await page.getByRole("button", { name: "Search", exact: true }).click();
  assert.match(await page.locator("#search-meta").innerText(), /8 nights/);
  await page.getByLabel("Check-out", { exact: true }).fill("2026-04-13");
  await page.getByRole("button", { name: "Search", exact: true }).click();
  assert.match(await page.locator("#modal-content").innerText(), /check-out after/);
  await page.getByRole("button", { name: "Close dialog" }).click();
}
