import test from "node:test";
import assert from "node:assert/strict";
import { autoTags, fixtures, makeArtifact, editArtifact, restoreVersion, filterArtifacts, validateInput } from "./assets/engine.js";
const now = "2026-11-13T10:00:00.000Z";
const input = { name: "A useful idea", type: "html", description: "", project: "", tags: "", content: "<p>Original idea</p>" };
const form = (record) => ({ ...record, tags: record.tags.join(",") });
test("rule tags are bounded, deduplicated and not generated by AI", () => {
  assert.deepEqual(autoTags("import React from 'react'; const dashboard = 'api';", "react"), ["react", "dashboard", "api"]);
  assert.deepEqual(autoTags("def backup():\n return 'SELECT count(*) FROM files'", "python"), ["python", "sql", "backup"]);
  assert.deepEqual(validateInput({ ...input, tags: " UI, ui, new idea " }).tags, ["ui", "new-idea"]);
  assert.throws(() => validateInput({ ...input, tags: "bad<tag>" }));
  assert.throws(() => validateInput({ ...input, tags: "a,b,c,d,e,f,g" }));
});
test("creation enforces uniqueness per collection and collision-safe stable slugs", () => {
  const a = makeArtifact([], input, "a", now);
  assert.equal(a.slug, "a-useful-idea");
  assert.throws(() => makeArtifact([a], input, "b", now));
  const b = makeArtifact([a], { ...input, project: "Different" }, "b", now);
  assert.equal(b.slug, "a-useful-idea-2");
  const renamed = editArtifact([a, b], a.id, { ...form(a), name: "Renamed idea" }, now);
  assert.equal(renamed.slug, a.slug);
  assert.throws(() => makeArtifact([{ ...a, deleted: true }], input, "c", now));
  assert.throws(() => makeArtifact(Array.from({ length: 20 }, (_, i) => ({ ...a, id: String(i) })), { ...input, name: "Something new" }, "z", now));
});
test("metadata edits preserve versions, source edits append and restore is non-destructive", () => {
  const a = makeArtifact([], input, "a", now);
  const meta = editArtifact([a], "a", { ...form(a), description: "New context", type: "text" }, now);
  assert.equal(meta.version, 1);
  assert.equal(meta.versions.length, 1);
  const b = editArtifact([meta], "a", { ...form(meta), content: "Changed source" }, now);
  assert.equal(b.version, 2);
  assert.equal(a.content, "<p>Original idea</p>");
  const c = restoreVersion(b, 1, now);
  assert.equal(c.version, 3);
  assert.equal(c.type, "text");
  assert.equal(c.description, "New context");
  assert.equal(c.content, a.content);
  assert.equal(c.versions[1].content, "Changed source");
  assert.throws(() => restoreVersion(c, 1, now));
  assert.throws(() => restoreVersion({ ...b, deleted: true }, 1, now));
});
test("source history cap and JSON guard preserve older snapshots", () => {
  let a = makeArtifact([], input, "a", now);
  for (let i = 2; i <= 10; i++) a = editArtifact([a], "a", { ...form(a), content: `Version ${i}` }, now);
  assert.equal(a.versions.length, 10);
  assert.throws(() => editArtifact([a], "a", { ...form(a), content: "Version 11" }, now));
  assert.throws(() => restoreVersion(a, 1, now));
  assert.equal(editArtifact([a], "a", { ...form(a), description: "Metadata still works" }, now).version, 10);
  assert.throws(() => validateInput({ ...input, type: "json", content: "{bad}" }));
  const text = makeArtifact([], input, "json-case", now);
  const json = editArtifact([text], text.id, { ...form(text), type: "json", content: '"Valid JSON"' }, now);
  assert.equal(json.type, "json");
  assert.throws(() => restoreVersion(json, 1, now));
});
test("search includes source and filters combine without mixing trash or favorites", () => {
  const samples = fixtures();
  assert.equal(samples.length, 8);
  assert.equal(filterArtifacts(samples, { query: "useState" })[0].id, "command");
  assert.equal(filterArtifacts(samples, { view: "favorites" }).length, 2);
  assert.equal(filterArtifacts(samples, { project: "Design system" }).length, 4);
  assert.deepEqual(filterArtifacts(samples, { type: "svg", tag: "identity" }).map((r) => r.id), ["orbit"]);
  const trashed = samples.map((record) => record.id === "orbit" ? { ...record, deleted: true } : record);
  assert.equal(filterArtifacts(trashed).length, 7);
  assert.equal(filterArtifacts(trashed, { view: "favorites" }).length, 1);
  assert.equal(filterArtifacts(trashed, { view: "trash" })[0].id, "orbit");
});
