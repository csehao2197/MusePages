export async function verify(page,nodeAssert){
  let checks=0;const assert=(condition,message)=>{nodeAssert.ok(condition,message);checks++;};
  await page.setViewportSize({width:1440,height:1000});await page.goto(page.url());
  assert(await page.locator('[data-design]').count()===8,'Eight original gift-card designs');
  for(const width of [1440,768,390]){
    await page.setViewportSize({width,height:1000});
    assert(await page.locator('#design-options').evaluate(container=>{const box=container.getBoundingClientRect();return [...container.children].every(child=>{const rect=child.getBoundingClientRect();return rect.left>=box.left-1&&rect.right<=box.right+1;});}),`Every design stays visible within selector at ${width}px`);
  }
  await page.setViewportSize({width:1440,height:1000});
  assert(await page.locator('#summary-total').innerText()==='$75.00','Default sample amount shown');
  assert(!await page.locator('.card-back').isVisible(),'Back-face personalization does not bleed through card front');
  await page.locator('#custom-amount').fill('9.99');
  assert(await page.locator('#add-cart').isDisabled(),'Below-minimum custom amount cannot enter cart');
  await page.locator('#custom-amount').fill('1000.01');
  assert(await page.locator('#buy-now').isDisabled(),'Above-maximum custom amount cannot enter checkout');
  await page.locator('#custom-amount').fill('10.001');
  assert(await page.locator('#custom-amount').getAttribute('aria-invalid')==='true','Fractions smaller than cents rejected');
  await page.locator('#custom-amount').fill('1000.00');
  assert(await page.locator('#summary-total').innerText()==='$1,000.00','Maximum amount accepted');
  await page.locator('#custom-amount').fill('10.01');
  assert(await page.locator('#summary-total').innerText()==='$10.01','Custom cent amount is exact');
  await page.locator('[data-delivery="physical"]').click();await page.locator('#premium').check();
  assert(await page.locator('#summary-total').innerText()==='$15.01','Physical premium packaging adds exactly five dollars');
  assert(await page.locator('#recipient-email').isDisabled()&&!await page.locator('#address').isDisabled(),'Delivery switch activates correct required fields');
  await page.locator('[data-delivery="digital"]').click();
  assert(await page.locator('#summary-total').innerText()==='$10.01','Digital mode excludes retained premium packaging');
  await page.locator('#recipient').fill('Alex <img src=x>');
  await page.locator('#sender').fill('Sam');
  await page.locator('#message').fill('a'.repeat(200));
  assert(await page.locator('#message-count').innerText()==='200 / 200','Message length counter matches browser limit');
  await page.locator('#message').fill('A little <img src=x> possibility.');
  await page.locator('#card-flip').click();
  assert(await page.locator('#card-flip').getAttribute('aria-pressed')==='true','Card flips to personal message');
  await page.waitForFunction(()=>getComputedStyle(document.querySelector('.card-front')).visibility==='hidden');
  assert(await page.locator('.card-back').isVisible(),'Flipped card exposes only personal-message side');
  assert(await page.locator('#back-message img').count()===0&&await page.locator('#summary-recipient img').count()===0,'Personalization stays safe text');
  await page.locator('[data-design="wedding"]').click();
  assert(await page.locator('#summary-design').innerText()==='Wedding'&&await page.locator('#card-flip').getAttribute('aria-pressed')==='false','Design choice updates summary and resets card front');
  const png=await page.evaluate(()=>{const canvas=document.createElement('canvas');canvas.width=300;canvas.height=200;const context=canvas.getContext('2d');context.fillStyle='#be9ed0';context.fillRect(0,0,300,200);return canvas.toDataURL('image/png').split(',')[1];});
  await page.locator('#upload').setInputFiles({name:'my-art.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')});
  await page.waitForFunction(()=>document.querySelector('#summary-design').textContent==='Your own image');
  assert(await page.locator('#card-front img').count()===1,'Valid image decodes locally into card preview');
  await page.locator('#upload').setInputFiles({name:'not-an-image.png',mimeType:'image/png',buffer:Buffer.from('not a PNG')});
  await page.waitForFunction(()=>document.querySelector('#upload-status').textContent.includes('could not be decoded'));
  assert(await page.locator('#summary-design').innerText()==='Your own image','Invalid file signature preserves previous design');
  await page.locator('#upload').setInputFiles({name:'unsafe.svg',mimeType:'image/svg+xml',buffer:Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"/>')});
  assert((await page.locator('#upload-status').innerText()).includes('Choose a PNG'),'SVG uploads rejected');
  await page.locator('[data-design="birthday"]').click();
  await page.locator('#save-design').click();await page.locator('#saved-open').click();
  assert(await page.locator('.dialog-design-list button').count()===1,'Saved designs filter real local choices');
  await page.keyboard.press('Escape');
  await page.locator('#recipient-email').fill('invalid');
  await page.locator('#buy-now').click();
  assert(!await page.locator('#dialog').isVisible(),'Invalid recipient email blocks preview checkout');
  await page.locator('#recipient-email').fill('alex@example.com');
  await page.locator('[name="timing"][value="schedule"]').check();
  await page.locator('#send-date').fill('2020-01-01');await page.locator('#buy-now').click();
  assert(!await page.locator('#dialog').isVisible(),'Past delivery date rejected');
  const future=await page.locator('#send-date').getAttribute('min');await page.locator('#send-date').fill(future);
  await page.locator('#reminder').check();
  const downloadPromise=page.waitForEvent('download');await page.locator('#download-reminder').click();const download=await downloadPromise;
  const chunks=[];for await(const chunk of await download.createReadStream())chunks.push(chunk);
  const ics=Buffer.concat(chunks).toString('utf8');
  assert(download.suggestedFilename()==='gift-card-reminder.ics'&&ics.includes(`DTSTART;VALUE=DATE:${future.replaceAll('-','')}`)&&ics.includes('DTEND;VALUE=DATE:'),'Calendar reminder downloads actual valid-date event');
  await page.locator('#email-preview').click();
  assert((await page.locator('#dialog-content').innerText()).includes('No email sent')&&await page.locator('#dialog-content img').count()===0,'Email template safe and explicit about no sending');
  await page.keyboard.press('Escape');
  await page.locator('#add-cart').click();
  assert((await page.locator('#dialog-content').innerText()).includes('$10.01')&&await page.locator('#cart-count').innerText()==='1','Valid digital gift becomes a local configuration snapshot');
  await page.keyboard.press('Escape');
  await page.locator('[data-delivery="physical"]').click();
  await page.locator('#address').fill('1 Example Lane');await page.locator('#city').fill('Example City');await page.locator('#region').fill('CA');await page.locator('#postal').fill('90210');
  await page.locator('#add-cart').click();
  assert((await page.locator('.cart-total').innerText()).includes('$25.02'),'Multiple digital and premium physical configurations total cents exactly');
  await page.locator('.cart-line button').first().click();
  assert(await page.locator('#cart-count').innerText()==='1'&&(await page.locator('.cart-total').innerText()).includes('$15.01'),'Removing snapshot updates local cart total');
  await page.keyboard.press('Escape');
  await page.locator('#buy-now').click();
  assert((await page.locator('#dialog-content').innerText()).includes('Nothing purchased')&&await page.locator('#cart-count').innerText()==='1','Express preview does not purchase or add another cart item');
  await page.keyboard.press('Escape');
  await page.locator('#card-number').fill('1234');await page.locator('#balance-form button').click();
  assert((await page.locator('#balance-result').innerText()).includes('16-digit'),'Balance input validates length');
  await page.locator('#card-number').fill('0000 0000 0000 0000');await page.locator('#balance-form button').click();
  assert((await page.locator('#balance-result').innerText()).includes('No matching local demo card'),'Unknown card does not invent a balance');
  await page.locator('#card-number').fill('1111 2222 3333 4444');await page.locator('#balance-form button').click();
  assert((await page.locator('#balance-result').innerText()).includes('$62.50')&&await page.locator('#balance-result li').count()===3,'Known fixture balance and ledger match');
  await page.locator('.faq-list summary').first().click();
  assert(await page.locator('.faq-list details').first().getAttribute('open')!==null,'FAQ expands with native keyboard-capable disclosure');
  await page.setViewportSize({width:390,height:900});
  assert(!await page.locator('#summary-details').evaluate(element=>element.open),'Mobile summary starts collapsed');
  await page.locator('#menu').click();
  assert(await page.locator('#nav').isVisible(),'Mobile navigation opens');
  await page.locator('#nav a').click();
  assert(await page.locator('#menu').getAttribute('aria-expanded')==='false','Mobile anchor closes menu');
  await page.locator('#mobile-add').click();
  assert(await page.locator('#dialog').isVisible()&&await page.locator('#cart-count').innerText()==='2','Mobile sticky action validates and adds actual configuration');
  await page.keyboard.press('Escape');await page.reload();
  assert(await page.locator('#cart-count').innerText()==='0'&&await page.locator('#saved-count').innerText()==='0','Refresh clears private memory-only cart and saved designs');
  return checks;
}
