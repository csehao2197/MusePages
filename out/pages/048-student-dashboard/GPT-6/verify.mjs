export async function verify(page, assert) {
  let checks = 0;
  await page.getByRole("button", { name: "View all courses" }).click();
  assert.equal(await page.locator(".course-card").count(), 5); checks++;
  await page.locator("#search").fill("machine");
  assert.equal(await page.locator(".course-card").count(), 1);
  assert.equal(await page.locator(".assignment:visible").count(), 1); checks += 2;
  await page.locator("#search").fill("nothing matches");
  assert.equal(await page.locator("#no-results").isVisible(), true); checks++;
  await page.locator("#search").fill("");
  await page.locator("[data-course='0']").first().click();
  await page.locator("#lesson-answer").fill("2, 4, 7");
  await page.getByRole("button", { name: "Check answer" }).click();
  assert.match(await page.locator("#lesson-feedback").textContent(), /right/); checks++;
  await page.keyboard.press("Escape");
  await page.locator("[data-assignment='0']").click();
  await page.locator("#work").setInputFiles({ name: "solution.txt", mimeType: "text/plain", buffer: Buffer.from("sample solution") });
  await page.getByRole("button", { name: "Preview submission", exact: true }).click();
  assert.match(await page.locator("#submission-result").textContent(), /solution\.txt/); checks++;
  await page.keyboard.press("Escape");
  assert.match(await page.locator(".assignment").first().textContent(), /Submitted locally/); checks++;
  await page.locator("[data-day='5']").click();
  assert.match(await page.locator("#day-classes").textContent(), /No classes/); checks++;
  await page.locator("[data-day='3']").click();
  assert.match(await page.locator("#day-classes").textContent(), /ML Lab/); checks++;
  const [download] = await Promise.all([page.waitForEvent("download"), page.locator("#calendar-export").click()]);
  assert.equal(download.suggestedFilename(), "brightpath-sample-week.ics"); checks++;
  await page.locator("[data-feedback='1']").click();
  assert.match(await page.locator("#dialog-content").textContent(), /constant extra space/); checks++;
  await page.keyboard.press("Escape");
  await page.locator("#mark-read").click();
  assert.equal(await page.locator("#notification-count").isHidden(), true); checks++;
  await page.locator(".top-actions [data-panel='messages']").click();
  await page.locator("#reply").fill("<b>Thanks for the feedback!</b>");
  await page.getByRole("button", { name: "Preview reply" }).click();
  assert.equal(await page.locator("#reply-preview").textContent(), "<b>Thanks for the feedback!</b>");
  assert.equal(await page.locator("#reply-preview b").count(), 0); checks += 2;
  await page.keyboard.press("Escape");
  await page.locator("#profile").click();
  assert.equal(await page.locator("#profile-menu").isVisible(), true); checks++;
  await page.getByRole("button", { name: "My Profile", exact: true }).click();
  assert.match(await page.locator("#dialog-content").textContent(), /Year 2/); checks++;
  await page.keyboard.press("Escape");
  await page.locator("[data-resource='Writing Center']").click();
  assert.match(await page.locator("#dialog-content").textContent(), /peer review/); checks++;
  await page.keyboard.press("Escape");
  await page.locator("#heatmap button").first().click();
  assert.match(await page.locator("#toast").textContent(), /sample record/); checks++;
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator(".mobile-nav [data-panel='more']").click();
  assert.match(await page.locator("#dialog-title").textContent(), /toolkit/); checks++;
  await page.keyboard.press("Escape");
  await page.reload();
  assert.doesNotMatch(await page.locator(".assignment").first().textContent(), /Submitted locally/); checks++;
  assert.equal(await page.locator(".heatmap button").count(), 84); checks++;
  return checks;
}
