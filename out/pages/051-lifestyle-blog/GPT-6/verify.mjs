export async function verify(page, nodeAssert) {
  let checks = 0;
  const assert = (condition, message) => { nodeAssert.ok(condition, message); checks++; };
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(page.url());
  assert(await page.locator('#picks-grid .story').count()===3,'Three editorial picks');
  assert(await page.locator('#latest-grid .story').count()===7,'Seven mixed-layout latest stories');
  await page.locator('.category-inner [data-category="Wellness"]').click();
  assert(await page.locator('#latest-grid .story').count()===2,'Wellness filters latest stories');
  await page.locator('.category-inner [data-category="Gift Guides"]').click();
  assert(await page.locator('#latest-empty').isVisible(),'Unimplemented gift guides returns honest empty state');
  await page.locator('#reset-filters').click();
  await page.locator('.search-icon').click();
  await page.locator('#search-query').fill('Copenhagen');
  await page.locator('#search-form button').click();
  assert(await page.locator('#picks-grid .story').count()===1,'Search discovers matching editorial pick');
  assert(await page.locator('#latest-grid .story').count()===0,'Search excludes unrelated latest stories');
  await page.locator('#view-all').click();
  await page.locator('[data-save="oaxaca"]').click();
  assert(await page.locator('#saved-count').textContent()==='1','Heart saves story this visit');
  await page.locator('#saved-toggle').click();
  assert(await page.locator('#latest-grid .story').count()===1,'Saved view contains only saved latest story');
  await page.locator('[data-save="oaxaca"]').click();
  assert(await page.locator('#latest-empty').isVisible(),'Unsave updates saved empty state');
  await page.locator('#view-all').click();
  await page.locator('.hero h1 [data-read="rest"]').click();
  assert(await page.locator('#reader').isVisible(),'Hero opens original readable editorial preview');
  assert((await page.locator('#reader-content').innerText()).includes('not a report of interviews'),'Fictional reporting disclosed');
  await page.keyboard.press('Escape');
  await page.locator('#explore-collection').click();
  await page.locator('#reader [data-read="wardrobe"]').click();
  assert((await page.locator('#reader-content h2').innerText()).includes('15 Pieces'),'Collection opens actual story');
  await page.keyboard.press('Escape');
  await page.locator('.category-inner [data-category="Interviews"]').click();
  assert(await page.locator('#latest-grid .story').count()===1,'Interview filter exposes concept with explicit limitation');
  await page.locator('#latest-grid h3 button').click();
  assert((await page.locator('#reader-content').innerText()).includes('No interview took place'),'No invented real-world interview');
  await page.keyboard.press('Escape');
  await page.locator('#view-all').click();
  await page.locator('#newsletter-email').fill('reader@example.com');
  await page.locator('#newsletter .primary').click();
  assert((await page.locator('#newsletter .form-status').innerText()).includes('No subscription created'),'Newsletter confirms local preview, not false signup');
  await page.locator('.social-photo').first().click();
  assert((await page.locator('#reader-content').innerText()).includes('not a live post') || (await page.locator('#reader-content').innerText()).includes('NOT A LIVE POST'),'Social imagery distinguished from live feed');
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:390,height:900});
  await page.locator('.menu-icon').click();
  assert(await page.locator('#primary-nav').isVisible(),'Mobile navigation opens');
  await page.locator('#primary-nav [data-category="Food"]').click();
  assert(await page.locator('.menu-icon').getAttribute('aria-expanded')==='false','Topic closes mobile menu');
  assert(await page.locator('#latest-grid .story').count()===1,'Mobile topic filter works');
  assert(await page.locator('.mobile-subscribe').isVisible(),'Mobile subscribe CTA available');
  assert(await page.locator('.social-photo').count()===6,'Six local social mood images');
  await page.evaluate(async () => {for(const image of document.images){image.loading='eager';}await Promise.all([...document.images].map(image => image.decode().catch(() => {})));});
  assert(await page.locator('img').evaluateAll(images => images.every(image => image.complete&&image.naturalWidth>0)),'All bundled photography decodes');
  await page.locator('#view-all').click();
  await page.evaluate(() => window.scrollTo(0,0));
  return checks;
}
