export async function verify(page, assert) {
  let checks = 0;
  assert.equal(await page.locator(".tutor-card").count(), 4); checks++;
  await page.locator("#search").fill("Math");
  await page.locator("#search-form button").click();
  assert.equal(await page.locator(".tutor-card").count(), 1);
  assert.match(await page.locator(".tutor-card").textContent(), /Sarah/); checks += 2;
  await page.locator("#clear-filters").click();
  await page.locator("#budget-filter").selectOption("30");
  assert.equal(await page.locator(".tutor-card").count(), 1);
  assert.match(await page.locator(".tutor-card").textContent(), /Carlos/); checks += 2;
  await page.locator("#subject-filter").selectOption("Math");
  assert.equal(await page.locator(".no-results").isVisible(), true); checks++;
  await page.locator("#clear-filters").click();
  await page.locator("[data-tutor='0']").click();
  assert.match(await page.locator("#booking-total").textContent(), /\$0.00/); checks++;
  await page.locator("#package").selectOption("six");
  assert.match(await page.locator("#booking-total").textContent(), /\$225.00/); checks++;
  await page.locator("#package").selectOption("ten");
  assert.match(await page.locator("#booking-total").textContent(), /\$382.50/); checks++;
  await page.locator("#learner").fill("<b>Alex</b>");
  await page.locator("#goal").fill("Understand calculus");
  await page.locator("#booking-form button").click();
  assert.match(await page.locator("#receipt").textContent(), /<b>Alex<\/b>/);
  assert.equal(await page.locator("#receipt b").count(), 0); checks += 2;
  await page.keyboard.press("Escape");
  await page.locator(".subject-card[data-subject='Piano']").click();
  assert.equal(await page.locator(".no-results").isVisible(), true); checks++;
  await page.locator("#clear-filters").click();
  await page.locator(".faq-list summary").first().click();
  assert.equal(await page.locator(".faq-list details").first().getAttribute("open"), ""); checks++;
  await page.locator("#email").fill("learner@example.com");
  await page.locator("#email-form button").click();
  assert.match(await page.locator("#email-status").textContent(), /no email was sent/); checks++;
  await page.locator("#teach [data-dialog='teach']").click();
  await page.locator("#teacher-name").fill("Taylor");
  await page.locator("#teacher-subject").fill("Statistics");
  await page.locator("#teacher-email").fill("teacher@example.com");
  await page.locator("#teach-form button").click();
  assert.match(await page.locator("#application-preview").textContent(), /Taylor · Statistics/); checks++;
  await page.keyboard.press("Escape");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator("#menu-toggle").click();
  assert.equal(await page.locator("header nav").isVisible(), true); checks++;
  await page.locator("header nav a[href='#subjects']").click();
  assert.equal(await page.locator("#menu-toggle").getAttribute("aria-expanded"), "false"); checks++;
  assert.equal(await page.locator(".mobile-cta").isVisible(), true); checks++;
  return checks;
}
