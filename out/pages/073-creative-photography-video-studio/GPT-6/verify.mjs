import {readFile} from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";

export async function verify(page,assert){
  let checks=0;
  const ok=(value,message)=>{assert.ok(value,message);checks++;};
  const eq=(actual,expected,message)=>{assert.deepEqual(actual,expected,message);checks++;};
  const folder=path.dirname(fileURLToPath(import.meta.url)),screens=path.join(folder,".checks");
  const base=new URL(page.url());base.search="";base.hash="";
  const external=[];
  const onRequest=request=>{if(new URL(request.url()).origin!==base.origin)external.push(request.url());};
  page.on("request",onRequest);
  const close=()=>page.locator("#close").click();
  const filter=id=>page.locator(`[data-filter="${id}"]`).click();
  const tab=id=>page.locator(`[data-package-tab="${id}"]`).click();
  const openForm=()=>page.locator("header [data-action=inquire]").click();
  await page.emulateMedia({reducedMotion:"reduce"});
  eq(await page.locator("#gallery .project").count(),6);
  eq(await page.locator("[role=tab]").count(),4);
  eq(await page.locator("#package-panel .package-row").count(),2);
  eq(await page.locator("[role=tab][aria-selected=true]").getAttribute("id"),"package-tab-photo");
  await page.evaluate(async()=>{for(const image of document.images)image.loading="eager";await Promise.all([...document.images].map(image=>image.decode()));});
  ok(await page.locator("img").evaluateAll(images=>images.every(i=>i.naturalWidth>0)),"All local photos decode");
  for(const [id,count] of [["yearbook",1],["wedding",2],["photo",2],["video",1],["all",6]]){
    await filter(id);
    eq(await page.locator("#gallery .project").count(),count);
    eq(await page.locator(`[data-filter="${id}"]`).getAttribute("aria-pressed"),"true");
    eq(new URL(page.url()).searchParams.get("work"),id);
  }
  await filter("photo");await filter("wedding");await page.goBack();
  await page.waitForURL(url=>url.searchParams.get("work")==="photo");
  eq(await page.locator("#gallery .project").count(),2,"History restores filter");
  await page.locator("[data-project=langkah]").click();
  eq(await page.locator("#dialog-title").textContent(),"Before the next step");
  await page.keyboard.press("ArrowRight");
  eq(await page.locator("#dialog-title").textContent(),"Where we grew");
  await page.keyboard.press("ArrowRight");
  eq(await page.locator("#dialog-title").textContent(),"Before the next step","Filtered loop excludes other categories");
  await page.keyboard.press("ArrowLeft");
  eq(await page.locator("#dialog-title").textContent(),"Where we grew");
  await page.screenshot({path:path.join(screens,"photo-lightbox.png")});
  await page.keyboard.press("Escape");
  eq(await page.locator("#dialog").evaluate(d=>d.open),false);
  eq(await page.evaluate(()=>document.activeElement?.dataset.project),"langkah","Opener focus restored");
  await page.locator(".hero [data-action=film]").click();
  eq(await page.locator("#film").count(),1);
  ok(await page.locator("[data-action=next]").isDisabled(),"Hero video remains in its one-item set");
  await page.waitForFunction(()=>document.querySelector("#film")?.readyState>=1);
  const metrics=await page.locator("#film").evaluate(v=>({duration:v.duration,width:v.videoWidth,height:v.videoHeight,paused:v.paused}));
  ok(metrics.duration>5.5&&metrics.duration<6.5,"Real six-second file");
  eq([metrics.width,metrics.height],[960,540]);
  eq(metrics.paused,true,"No autoplay");
  await page.locator("#film").evaluate(v=>v.play());
  await page.waitForFunction(()=>document.querySelector("#film").currentTime>.25);
  ok(await page.locator("#film").evaluate(v=>!v.paused),"Native player advances");
  const frames=await page.locator("#film").evaluate(async v=>{
    const canvas=document.createElement("canvas");canvas.width=96;canvas.height=54;const ctx=canvas.getContext("2d");
    const sample=async delay=>{await new Promise(resolve=>setTimeout(resolve,delay));await new Promise((resolve,reject)=>{const timeout=setTimeout(()=>reject(Error("No presented video frame")),5000);v.requestVideoFrameCallback(()=>{clearTimeout(timeout);resolve();});});ctx.drawImage(v,0,0,96,54);return canvas.toDataURL();};
    const result=[await sample(300),await sample(1500)];v.pause();return result;
  });
  ok(frames[0]!==frames[1],"Video has real changing frames");
  await page.screenshot({path:path.join(screens,"film-player.png")});
  await page.locator("#film").evaluate(v=>{window.__lenteraVideo=v;return v.play();});
  await close();
  ok(await page.evaluate(()=>window.__lenteraVideo.paused),"Closing stops playback");
  await page.evaluate(()=>delete window.__lenteraVideo);
  await filter("all");
  await page.locator("[data-project=cahaya]").click();
  await page.locator("#film").evaluate(v=>v.play());
  await page.evaluate(()=>{window.__lenteraVideo=document.querySelector("#film");});
  await page.locator("[data-action=next]").click();
  eq(await page.locator("#film").count(),0,"Advancing replaces player");
  ok(await page.evaluate(()=>window.__lenteraVideo.paused),"Advancing stops previous video");
  await page.evaluate(()=>delete window.__lenteraVideo);
  await close();
  for(const id of ["yearbook","wedding","photo","video"]){
    await tab(id);
    eq(await page.locator("#package-panel").getAttribute("aria-labelledby"),"package-tab-"+id);
    eq(await page.locator("#package-panel .package-row").count(),2);
    eq(new URL(page.url()).searchParams.get("package"),id);
  }
  await page.keyboard.press("Home");eq(await page.evaluate(()=>document.activeElement.id),"package-tab-yearbook");
  await page.keyboard.press("End");eq(await page.evaluate(()=>document.activeElement.id),"package-tab-video");
  await page.keyboard.press("ArrowRight");eq(await page.evaluate(()=>document.activeElement.id),"package-tab-yearbook");
  await page.keyboard.press("ArrowLeft");eq(await page.evaluate(()=>document.activeElement.id),"package-tab-video");
  await tab("yearbook");
  await page.locator("[data-package=yb-cerita]").click();
  const form=page.locator("#inquiry-form"),quantity=form.locator("[name=quantity]"),city=form.locator("[name=city]"),date=form.locator("[name=date]"),note=form.locator("[name=note]");
  eq(await form.locator("[name=package]").inputValue(),"yb-cerita");
  eq(await quantity.inputValue(),"30");
  ok((await page.locator("#estimate").textContent()).includes("5,250,000"),"Per-person estimate");
  await quantity.fill("29");
  eq(await quantity.evaluate(i=>i.checkValidity()),false);
  eq(await page.locator("#estimate").textContent(),"Invalid participant count");
  await quantity.fill("30.5");eq(await quantity.evaluate(i=>i.checkValidity()),false);
  await quantity.fill("501");eq(await quantity.evaluate(i=>i.checkValidity()),false);
  await quantity.fill("500");
  ok((await page.locator("#estimate").textContent()).includes("87,500,000"),"Maximum estimate");
  await quantity.fill("32");
  ok((await page.locator("#estimate").textContent()).includes("5,600,000"));
  const today=await date.getAttribute("min");
  await date.fill("2020-01-01");eq(await date.evaluate(i=>i.checkValidity()),false);
  await date.fill(today);
  await city.fill("   ");
  await form.locator("button").first().click();
  ok((await page.locator("#form-error").textContent()).includes("Complete"),"Whitespace location rejected");
  await city.fill("Yogyakarta & Solo <demo>");
  await note.fill("Family, group photos + friend #1");
  eq(await city.getAttribute("maxlength"),"50");eq(await note.getAttribute("maxlength"),"300");
  await page.screenshot({path:path.join(screens,"yearbook-inquiry.png")});
  const storageBefore=await page.evaluate(()=>({local:JSON.stringify(localStorage),session:JSON.stringify(sessionStorage)}));
  await form.locator("button").first().click();
  const draft=await page.locator("#draft").inputValue();
  ok(draft.includes("Participants: 32")&&draft.includes("5,600,000"),"Draft contains calculated total");
  ok(draft.includes("Yogyakarta & Solo <demo>")&&draft.includes("Family, group photos + friend #1"),"Input remains plain text");
  eq(await page.locator("#dialog-content demo").count(),0,"User text cannot become markup");
  ok(draft.includes("NOT A BOOKING")&&draft.includes("not been sent"));
  const link=page.locator("#whatsapp"),url=new URL(await link.getAttribute("href"));
  eq(url.origin+url.pathname,"https://wa.me/","No invented recipient");
  eq(url.searchParams.get("text"),draft,"Share URL encodes exact draft");
  eq(await link.getAttribute("target"),"_blank");
  ok((await link.getAttribute("rel")).includes("noopener"));
  ok((await page.locator("#dialog-content").textContent()).includes("choose a recipient"));
  const downloadPromise=page.waitForEvent("download");
  await page.locator("[data-action=download]").click();
  const download=await downloadPromise;
  eq(download.suggestedFilename(),"lentera-unsent-message.txt");
  eq(await readFile(await download.path(),"utf8"),draft+"\n","Actual downloaded bytes");
  await page.evaluate(()=>{Object.defineProperty(navigator,"clipboard",{configurable:true,value:{writeText:async text=>{window.__lenteraClipboard=text;}}});});
  await page.locator("[data-action=copy]").click();
  eq(await page.evaluate(()=>window.__lenteraClipboard),draft,"Copy passes exact text");
  await page.evaluate(()=>{Object.defineProperty(navigator,"clipboard",{configurable:true,value:{writeText:async()=>{throw Error("Unavailable");}}});delete window.__lenteraClipboard;});
  await page.locator("[data-action=copy]").click();
  eq(await page.locator("#draft").evaluate(t=>t.selectionEnd-t.selectionStart),draft.length,"Clipboard fallback selects text");
  eq(await page.evaluate(()=>({local:JSON.stringify(localStorage),session:JSON.stringify(sessionStorage)})),storageBefore,"No form persistence");
  await close();eq(await page.locator("#draft").count(),0,"Closing clears sensitive DOM");
  await openForm();eq(await city.inputValue(),"","Form does not restore prior input");
  await form.locator("[name=package]").selectOption("fg-personal");
  eq(await page.locator("#quantity-label").isVisible(),false);
  eq(await quantity.inputValue(),"1");
  ok((await page.locator("#estimate").textContent()).includes("275,000"));
  await form.locator("[name=package]").selectOption("yb-lengkap");
  eq(await page.locator("#quantity-label").isVisible(),true);eq(await quantity.inputValue(),"30");
  ok((await page.locator("#estimate").textContent()).includes("7,350,000"));
  await close();
  await page.locator(".section-heading [data-action=credits]").click();
  eq(await page.locator(".credits a").count(),6);
  ok((await page.locator(".credits").textContent()).includes("design.md"));
  await close();
  await page.locator("details summary").first().click();
  eq(await page.locator("details").first().getAttribute("open"),"");
  await page.locator("details summary").first().click();
  const invalid=new URL(base);invalid.search="?work=unknown&package=unknown";
  await page.goto(invalid.href);
  eq(await page.locator("#gallery .project").count(),6);
  eq(await page.locator("[aria-selected=true]").getAttribute("id"),"package-tab-photo");
  await page.setViewportSize({width:390,height:900});
  await page.locator("#menu").click();eq(await page.locator("#menu").getAttribute("aria-expanded"),"true");
  await page.keyboard.press("Escape");eq(await page.locator("#menu").getAttribute("aria-expanded"),"false");
  await page.locator("#menu").click();await page.locator("#navigation a[href='#packages']").click();
  eq(await page.locator("#menu").getAttribute("aria-expanded"),"false");
  await page.locator('[data-category="wedding"]').click();
  eq(await page.locator("#gallery .project").count(),2);
  await page.locator(".floating").click();
  await form.locator("[name=package]").selectOption("wo-story");await date.fill(today);await city.fill("Bandung");
  await form.locator("button").first().click();
  ok(!(await page.locator("#draft").inputValue()).includes("Participants:"),"Fixed package uses one event");
  await page.screenshot({path:path.join(screens,"mobile-draft.png"),fullPage:true});
  ok(await page.locator("#dialog").evaluate(d=>d.scrollWidth<=d.clientWidth+1),"Mobile dialog fits");
  await close();await filter("all");await tab("photo");
  await page.evaluate(()=>scrollTo(0,0));
  for(const width of [1440,1024,768,390,320]){
    await page.setViewportSize({width,height:900});
    ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),"No horizontal overflow "+width);
  }
  eq(external,[],"No external requests without explicit outbound navigation");
  page.off("request",onRequest);
  await page.setViewportSize({width:1440,height:900});
  return checks;
}
