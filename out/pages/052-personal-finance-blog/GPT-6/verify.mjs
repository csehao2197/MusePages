export async function verify(page, nodeAssert) {
  let checks=0;
  const assert=(condition,message)=>{nodeAssert.ok(condition,message);checks++;};
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(page.url());
  assert(await page.locator('.article').count()===6,'Six original latest article previews');
  await page.locator('.pillar[data-topic="Investing"]').click();
  assert(await page.locator('.article').count()===2,'Investment archive includes featured and IRA guide');
  await page.locator('#all-articles').click();
  await page.locator('#open-search').click();
  await page.locator('#search').fill('Roth');
  await page.locator('#search-form .primary').click();
  assert(await page.locator('.article').count()===1,'Title search filters articles');
  await page.locator('#open-search').click();
  await page.locator('#search').fill('<img src=x>');
  await page.locator('#search-form .primary').click();
  assert(await page.locator('#article-empty').isVisible(),'Unmatched search returns empty state');
  assert(await page.locator('#article-status img').count()===0,'Search query rendered as text');
  await page.locator('#clear-search').click();
  await page.locator('.hero-cta').click();
  assert((await page.locator('#reader-content').innerText()).includes('Investments can lose value'),'Featured article contains real educational text and risk disclosure');
  await page.keyboard.press('Escape');
  await page.locator('#income').fill('4500');
  assert(await page.locator('#needs').innerText()==='$2,250.00','Needs allocation correct');
  assert(await page.locator('#wants').innerText()==='$1,350.00','Wants allocation correct');
  assert(await page.locator('#savings').innerText()==='$900.00','Savings allocation correct');
  await page.locator('#income').fill('1,000.01');
  assert(await page.locator('#needs').innerText()==='$500.01','Needs rounds to cents');
  assert(await page.locator('#wants').innerText()==='$300.00'&&await page.locator('#savings').innerText()==='$200.00','Allocations sum exactly to income');
  for(const invalid of ['-100','12,34','1e6','1000001','0','12.345']){
    await page.locator('#income').fill(invalid);
    assert(await page.locator('#income').getAttribute('aria-invalid')==='true'&&await page.locator('#needs').innerText()==='—',`Invalid income ${invalid} clears stale calculation`);
  }
  await page.locator('#income').fill('4,500');
  const budgetDownload=page.waitForEvent('download');
  await page.locator('.tool-grid [data-download="budget"]').click();
  const budget=await budgetDownload;
  assert(budget.suggestedFilename()==='monthly-budget-template.csv','Budget CSV downloads without prompt prefix');
  const budgetStream=await budget.createReadStream();let budgetText='';for await(const chunk of budgetStream)budgetText+=chunk;
  assert(budgetText.includes('=SUM(B2:B8)')&&budgetText.includes('Minimum debt payments'),'Budget CSV includes working total and category structure');
  const netDownload=page.waitForEvent('download');
  await page.locator('.tool-grid [data-download="networth"]').click();
  const net=await netDownload;
  const netStream=await net.createReadStream();let netText='';for await(const chunk of netStream)netText+=chunk;
  assert(netText.includes('Net worth,=B5-B9'),'Net worth template subtracts liabilities from assets');
  await page.locator('#open-debt').click();
  for(const prefix of ['a','b']){
    await page.locator(`[name="${prefix}Balance"]`).fill('1000');
    await page.locator(`[name="${prefix}Rate"]`).fill('0');
    await page.locator(`[name="${prefix}Minimum"]`).fill('100');
  }
  await page.locator('[name="extra"]').fill('0');
  await page.locator('#debt-form .primary').click();
  assert(await page.locator('#debt-result p').filter({hasText:'10 months · $0.00 interest'}).count()===2,'Zero-APR debts repay in ten months under both strategies');
  await page.locator('[name="bRate"]').fill('12');
  await page.locator('[name="extra"]').fill('100');
  assert(await page.locator('#debt-result').innerText()==='','Changing debt inputs clears stale estimates');
  await page.locator('#debt-form .primary').click();
  const costTexts=await page.locator('.debt-comparison p').allTextContents();
  const costs=costTexts.map(value=>Number(value.match(/\$([\d,]+\.\d{2})/)[1].replaceAll(',','')));
  assert(costs[1]<costs[0],'Avalanche reduces interest when the larger remaining balance has higher APR');
  await page.locator('[name="extra"]').fill('0');
  await page.locator('[name="bRate"]').fill('0');
  await page.locator('[name="aRate"]').fill('20');
  await page.locator('[name="aMinimum"]').fill('.01');
  await page.locator('[name="bMinimum"]').fill('.01');
  await page.locator('#debt-form .primary').click();
  assert((await page.locator('#debt-result').innerText()).includes('No payoff within 600 months'),'Non-amortizing payments stop safely instead of false payoff date');
  await page.keyboard.press('Escape');
  await page.locator('#email').fill('reader@example.com');
  await page.locator('#signup .primary').click();
  assert((await page.locator('#signup-status').innerText()).includes('No subscription created'),'Newsletter only previews local signup');
  await page.setViewportSize({width:390,height:900});
  await page.locator('#menu').click();
  assert(await page.locator('#nav').isVisible(),'Mobile menu opens');
  await page.locator('#nav [data-topic="Debt"]').click();
  assert(await page.locator('.article').count()===1&&await page.locator('#menu').getAttribute('aria-expanded')==='false','Mobile category filtering closes menu');
  assert(await page.locator('.footer-grid details[open]').count()===0,'Footer initially collapses on mobile');
  await page.locator('.footer-grid summary').first().click();
  assert(await page.locator('.footer-grid details').first().getAttribute('open')!==null,'Mobile footer accordion expands');
  await page.locator('#all-articles').click();
  await page.evaluate(()=>window.scrollTo(0,0));
  return checks;
}
