import { readFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import sheet from "./assets/cheatsheet.json" with { type: "json" };
import { copyText } from "./assets/engine.js";
export async function verify(page, assert) {
  let checks = 0;
  const eq = (actual, expected, message = "Values match the expected behavior") => { assert.equal(actual, expected, message); checks++; };
  const ok = (value, message = "Behavior is verified") => { assert.ok(value, message); checks++; };
  const folder = new URL(".checks/", import.meta.url);
  const base = page.url();
  await page.context().grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.locator(".command-row").last().waitFor();
  eq(await page.locator(".reference-section").count(), 8);
  eq(await page.locator(".command-row").count(), 32);
  eq(await page.locator("details[open]").count(), 0);
  eq(await page.locator("#result-count").innerText(), "32 essentials across 8 sections");
  ok((await page.locator(".snapshot").innerText()).includes("13 Nov 2026"));
  const runtime = await page.evaluate(async () => (await import("./assets/catalog.js")).default);
  eq(JSON.stringify(runtime), JSON.stringify(sheet), "Browser data equals the curated source JSON");
  for (const section of sheet.sections) {
    await page.locator(`[data-section="${section.id}"]`).click();
    eq(await page.locator(".reference-section").count(), 1);
    eq(await page.locator(".command-row").count(), 4);
    eq(await page.locator(`[data-section="${section.id}"]`).getAttribute("aria-pressed"), "true");
  }
  await page.locator("#all-sections").click();
  await page.keyboard.press("Control+k");
  ok(await page.locator("#search").evaluate((el) => document.activeElement === el));
  await page.locator("#search").fill("NON-INTERACTIVE -p");
  eq(await page.locator(".command-row").count(), 1);
  eq(await page.locator(".command-row").getAttribute("id"), "print-mode");
  await page.locator("#search").fill("trace response");
  eq(await page.locator(".command-row").getAttribute("id"), "trace-request");
  await page.locator("#search").fill("[");
  eq(await page.locator(".command-row").count(), 0);
  ok(await page.locator("#empty").isVisible());
  ok(await page.locator("#expand-all").isDisabled());
  await page.locator("#reset-filters").click();
  eq(await page.locator(".command-row").count(), 32);
  await page.locator("#search").fill("ctrl");
  eq(await page.locator(".command-row").count(), 4);
  await page.locator("#expand-all").click();
  eq(await page.locator("details[open]").count(), 4);
  eq(await page.locator("#expand-all span").innerText(), "Collapse all");
  await page.screenshot({path:fileURLToPath(new URL("desktop-expanded.png",folder)),fullPage:true});
  await page.locator("#expand-all").click();
  eq(await page.locator("details[open]").count(), 0);
  const summary = page.locator("#interrupt summary");
  await summary.focus(); await page.keyboard.press("Enter");
  ok(await page.locator("#interrupt details").getAttribute("open") !== null, "Native accordion opens from keyboard");
  await page.keyboard.press("Enter");
  eq(await page.locator("#interrupt details").getAttribute("open"), null);
  await page.locator("#clear-search").click();
  eq(await page.locator("#search").inputValue(), "");
  for (const item of sheet.sections.flatMap((section) => section.items)) {
    await page.locator(`[data-copy="${item.id}"]`).click();
    eq(await page.evaluate(() => navigator.clipboard.readText()), copyText(item), `Clipboard contains the exact ${item.id} example`);
  }
  await page.locator("#copy-hero").click();
  eq(await page.evaluate(() => navigator.clipboard.readText()), "claude --continue");
  await page.locator('[data-save="help"]').click();
  eq(await page.locator("#saved-count").innerText(), "1");
  eq(await page.locator('[data-save="help"]').getAttribute("aria-pressed"), "true");
  await page.locator("#saved-toggle").click();
  eq(await page.locator(".command-row").count(), 1);
  eq(await page.locator(".command-row").getAttribute("id"), "help");
  await page.locator('[data-section="keyboard-shortcuts"]').click();
  ok(await page.locator("#empty").isVisible());
  await page.locator("#all-sections").click();
  await page.locator('[data-save="help"]').click();
  eq(await page.locator("#saved-count").innerText(), "0");
  ok(await page.locator("#empty").isVisible());
  await page.locator("#reset-filters").click();
  await page.locator("#help summary").click();
  await page.locator('[data-link="help"]').click();
  eq(await page.evaluate(() => navigator.clipboard.readText()), `${base}#help`);
  const sources = await page.locator(".entry-links a").evaluateAll((links) => links.map((a) => ({href:a.href,rel:a.rel,target:a.target})));
  eq(sources.length, 32);
  ok(sources.every((link) => link.href.startsWith("https://code.claude.com/docs/en/") && link.rel.includes("noopener") && link.target === "_blank"));
  await page.locator("#open-sources").click();
  ok(await page.locator("#sources-dialog").isVisible());
  eq(await page.locator("#source-list a").count(), 8);
  ok((await page.locator("#sources-dialog").innerText()).includes("No crawler, cron"));
  await page.keyboard.press("Escape");
  ok(!(await page.locator("#sources-dialog").isVisible()));
  await page.locator("#open-changelog").click();
  ok((await page.locator("#changelog-dialog").innerText()).includes("not the Claude Code release history"));
  await page.locator('[data-close="changelog-dialog"]').click();
  const downloadWait = page.waitForEvent("download");
  await page.locator(".pdf-button").click();
  const download = await downloadWait;
  eq(download.suggestedFilename(), "claude-code-field-guide.pdf");
  const pdfPath = new URL("downloaded-guide.pdf",folder);
  await download.saveAs(fileURLToPath(pdfPath));
  const pdf = await readFile(pdfPath);
  const artifacts = JSON.parse(await readFile(new URL("assets/artifacts.json",import.meta.url),"utf8"));
  eq(pdf.subarray(0,5).toString(), "%PDF-");
  eq(createHash("sha256").update(pdf).digest("hex"),artifacts.pdfSha256);
  eq([...pdf.toString("latin1").matchAll(/\/Type\s*\/Page\b/g)].length,artifacts.pages);
  ok(artifacts.pages >= 2 && artifacts.entries === 32);
  await page.goto(new URL("assets/reference-print.html",base).href);
  eq(await page.locator("article[data-entry]").count(),32);
  eq(await page.locator("section").count(),8);
  for (const item of sheet.sections.flatMap((section) => section.items)) {
    const printed = await page.locator(`[data-entry="${item.id}"]`).innerText();
    ok(printed.includes(item.explanation) && printed.includes(copyText(item)) && printed.includes(item.source), `Print reference contains the complete ${item.id} entry`);
  }
  await page.emulateMedia({media:"print"});
  ok(await page.evaluate(() => [...document.styleSheets[0].cssRules].some((rule) => rule.cssText.startsWith("@page") && rule.cssText.includes("a4"))));
  await page.screenshot({path:fileURLToPath(new URL("print-view.png",folder))});
  await page.emulateMedia({media:"screen"});
  await page.goto(`${base}#mcp-http`);
  await page.locator("#mcp-http details[open]").waitFor();
  eq(await page.locator(".command-row").count(),32);
  ok(await page.locator("#mcp-http .entry-body").isVisible());
  await page.setViewportSize({width:390,height:900});
  await page.locator("#theme-toggle").click();
  ok(await page.locator("body").evaluate((el) => el.classList.contains("light")));
  eq(await page.locator("#theme-toggle").getAttribute("aria-label"),"Switch to dark theme");
  ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth+1));
  await page.locator("#mcp-http").scrollIntoViewIfNeeded();
  await page.screenshot({path:fileURLToPath(new URL("mobile-light-entry.png",folder))});
  await page.locator("#theme-toggle").click();
  eq(await page.locator("#theme-toggle").getAttribute("aria-label"),"Switch to light theme");
  await page.setViewportSize({width:320,height:900});
  await page.locator("#open-newsletter").click();
  ok((await page.locator("#newsletter-dialog").innerText()).includes("No address is transmitted"));
  await page.locator("#newsletter-email").fill("invalid");
  await page.locator("#newsletter-consent").check();
  await page.locator("#newsletter-form button[type=submit]").click();
  ok(!(await page.locator("#newsletter-email").evaluate((el) => el.validity.valid)));
  eq(await page.locator("#newsletter-result").innerText(),"");
  await page.locator("#newsletter-email").fill("reader@example.com");
  await page.locator("#newsletter-consent").uncheck();
  await page.locator("#newsletter-form button[type=submit]").click();
  ok(!(await page.locator("#newsletter-consent").evaluate((el) => el.validity.valid)));
  await page.locator("#newsletter-consent").check();
  await page.locator("#newsletter-email").focus();
  await page.screenshot({path:fileURLToPath(new URL("mobile-signup-draft.png",folder))});
  const remotePosts = [];
  const watch = (request) => { if (request.method() !== "GET") remotePosts.push(request.url()); };
  page.on("request",watch);
  const draftWait = page.waitForEvent("download");
  await page.locator("#newsletter-form button[type=submit]").click();
  const draft = await draftWait;
  const draftFile = new URL("downloaded-unsent-draft.txt",folder);
  await draft.saveAs(fileURLToPath(draftFile));
  const text = await readFile(draftFile,"utf8");
  ok(text.includes("Email: reader@example.com") && text.includes("NOT SENT"));
  eq(draft.suggestedFilename(),"unsent-update-request.txt");
  eq(await page.locator("#newsletter-email").inputValue(),"");
  ok((await page.locator("#newsletter-result").innerText()).includes("you are not subscribed"));
  eq(remotePosts.length,0);
  page.off("request",watch);
  ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth+1));
  await page.keyboard.press("Escape");
  await page.goto(base);
  await page.reload();
  eq(await page.locator("#saved-count").innerText(),"0");
  eq(await page.locator("details[open]").count(),0);
  eq(await page.locator(".command-row").count(),32);
  eq(await page.evaluate(() => localStorage.length+sessionStorage.length),0);
  eq(await page.locator("#search").inputValue(),"");
  eq(await page.locator("#newsletter-email").inputValue(),"");
  ok(await page.evaluate(() => [...document.querySelectorAll("svg use")].filter((use) => use.closest("dialog") === null && use.getBoundingClientRect().width > 0).every((use) => use.getBBox().width > 0)), "Visible symbols are loaded");
  return checks;
}
