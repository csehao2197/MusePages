export async function exercise(page, assert, width) {
  let scenarios = 0;
  const check = (condition, message) => { assert.ok(condition, `${width}px: ${message}`); scenarios++; };
  const equals = (actual, expected, message) => { assert.deepEqual(actual, expected, `${width}px: ${message}`); scenarios++; };
  const reset = async () => { await page.locator("#clear-filters").click(); };
  const openFilters = async () => {
    if (width <= 720 && !(await page.locator("#filter-shell").evaluate((element) => element.classList.contains("expanded")))) await page.locator("#mobile-filter").click();
  };
  const cards = page.locator("#deals-grid .deal-card");
  const ids = () => cards.evaluateAll((elements) => elements.map((element) => element.dataset.deal));
  const prices = () => cards.evaluateAll((elements) => elements.map((element) => Number(element.dataset.price)));
  const openCard = async (id) => {
    await page.locator(`#deals-grid [data-deal="${id}"] .button[data-open]`).click();
    check(await page.locator("#deal-dialog").isVisible(), "Deal details open");
  };
  const closeDeal = () => page.locator("#deal-dialog [data-close]").click();
  equals(await cards.count(), 9, "Initial nine sample deals");
  equals(await page.locator("#mobile-count").textContent(), "17", "Live total reflects real local catalogue, not fixture 47");
  equals((await ids()).slice(0, 8), ["santorini", "cancun", "kyoto", "amalfi", "maldives", "reykjavik", "marrakech", "phuket"], "Eight required initial offers preserved");
  check(!(await page.locator("body").innerText()).includes("008-"), "No public prompt-number prefix");
  equals(await page.locator("#flash-play").getAttribute("aria-pressed"), "false", "Reduced-motion preference disables autoplay initially");
  await page.locator("#flash-next").click();
  check(await page.locator("#flash-track").evaluate((element) => element.scrollLeft > 0), "Manual carousel next scrolls");
  await page.locator("#flash-prev").click();
  check(await page.locator("#flash-track").evaluate((element) => element.scrollLeft < 3), "Manual carousel previous returns");
  await page.locator("#flash-track").focus();
  await page.keyboard.press("ArrowRight");
  check(await page.locator("#flash-track").evaluate((element) => element.scrollLeft > 0), "Keyboard carousel navigation");
  await page.locator("#flash-play").click();
  equals(await page.locator("#flash-play").getAttribute("aria-pressed"), "true", "User can explicitly play carousel");
  await page.locator("#flash-play").click();
  equals(await page.locator("#flash-play").getAttribute("aria-pressed"), "false", "Carousel can be paused");
  await page.locator("#load-more").click();
  equals(await cards.count(), 13, "Load more reveals four actual offers");
  await page.locator("#load-more").click();
  equals(await cards.count(), 17, "Load more reaches catalogue end without duplicates");
  equals(new Set(await ids()).size, 17, "All loaded IDs are unique");
  check(await page.locator("#load-more").isHidden(), "Load button hidden at end");
  await openFilters();
  await page.locator("#filter-region").selectOption("Asia");
  await page.locator("#filter-type").selectOption("Hotels");
  await page.locator("#filter-budget").selectOption("mid");
  equals(await ids(), ["phuket", "bali"], "Type, destination and budget filters combine");
  equals(await page.locator("#result-count").textContent(), "2 deals found", "Filtered counter updates");
  await page.locator("#filter-dates").selectOption("0");
  equals(await ids(), ["bali"], "Date availability combines with other filters");
  await page.locator("#filter-region").selectOption("Africa");
  check(await page.locator("#empty-results").isVisible(), "No-match state is meaningful");
  equals(await cards.count(), 0, "No-match state has no false placeholder offers");
  await page.locator("#empty-reset").click();
  equals(await cards.count(), 9, "Empty state reset restores real offers");
  await page.locator("#filter-budget").selectOption("under");
  check((await prices()).every((price) => price < 300), "Under-300 price boundary");
  equals(await cards.count(), 4, "Under-300 matches actual samples");
  await page.locator("#filter-budget").selectOption("mid");
  check((await prices()).every((price) => price >= 300 && price <= 700), "300–700 inclusive budget");
  await page.locator("#filter-budget").selectOption("high");
  check((await prices()).every((price) => price > 700 && price <= 1500), "Over-700 to 1500 budget");
  await page.locator("#filter-budget").selectOption("luxury");
  equals(await ids(), ["maldives"], "1500-plus budget");
  await reset();
  await page.locator("#sort").selectOption("price");
  const sortedPrices = await prices();
  equals(sortedPrices, [...sortedPrices].sort((a, b) => a - b), "Price sort uses numeric values");
  await page.locator("#sort").selectOption("savings");
  const savings = await cards.evaluateAll((elements) => elements.map((element) => Number(element.dataset.savings)));
  equals(savings, [...savings].sort((a, b) => b - a), "Savings sort uses actual price difference");
  await page.locator("#sort").selectOption("soon");
  const departures = await cards.evaluateAll((elements) => elements.map((element) => Number(element.dataset.departure)));
  equals(departures, [...departures].sort((a, b) => a - b), "Departing-soon sort");
  await page.locator("#to-city").fill("kyoto");
  await page.locator("#from-city").fill("New York");
  await page.locator("#search-dates").selectOption("0");
  await page.locator("#travelers").selectOption("3");
  await page.locator("#deal-search button[type=submit]").click();
  equals(await ids(), ["kyoto"], "Search captures destination, origin and month before resetting filters");
  check((await page.locator("#deals-grid .trip-details").textContent()).includes("3 adults"), "Traveler selection survives search");
  await page.locator("#from-city").fill("Not A Sample Departure");
  await page.locator("#deal-search button[type=submit]").click();
  check(await page.locator("#empty-results").isVisible(), "Unknown origin does not fabricate fares");
  await reset();
  await page.locator("#to-city").fill("cancun");
  await page.locator("#deal-search button[type=submit]").click();
  equals(await ids(), ["cancun"], "Accent-insensitive destination matching");
  await reset();
  await page.locator("#category-grid [data-type=Cars]").click();
  equals(await ids(), ["lisbon-car"], "Car category filters a genuine local rental");
  await openCard("lisbon-car");
  equals(await page.locator("#detail-total").textContent(), "$149", "Rental price not multiplied by travelers");
  await closeDeal();
  await page.locator("#category-grid [data-type=Experiences]").click();
  equals(await ids(), ["iceland-tour"], "Experience category offers actual local fixture");
  await page.locator("#see-portugal").click();
  equals(await ids(), ["lisbon", "algarve", "porto", "lisbon-car"], "Portugal spotlight filters only Portugal");
  await reset();
  await page.locator('#deals-grid [data-save="santorini"]').click();
  equals(await page.locator("#saved-count").textContent(), "1", "Saved count updates");
  await page.locator("#show-saved").click();
  equals(await ids(), ["santorini"], "Saved view contains only saved deal");
  await page.reload({ waitUntil: "networkidle" });
  equals(await page.locator("#saved-count").textContent(), "1", "Saved deal persists across reload");
  await page.locator("#show-saved").click();
  equals(await ids(), ["santorini"], "Saved view survives persisted data");
  await page.locator('#deals-grid [data-save="santorini"]').click();
  check(await page.locator("#empty-results").isVisible(), "Removing last saved deal shows empty state");
  await reset();
  await page.locator("#clear-history").click();
  await page.locator('#recommendations [data-open="athens"]').click();
  await page.locator('#deal-dialog [data-save="athens"]').click();
  await closeDeal();
  check(await page.evaluate(() => document.activeElement.matches('#recently-viewed [data-open="athens"]')), "Closing a re-rendered recommendation restores focus to its recent-history entry");
  await page.locator("#show-saved").click();
  equals(await ids(), ["athens"], "Saved view includes recommendation-only offers outside main catalogue");
  await page.locator('#deals-grid [data-save="athens"]').click();
  await reset();
  for (const id of ["santorini", "cancun", "kyoto", "amalfi", "maldives"]) {
    await openCard(id);
    await closeDeal();
  }
  equals(await page.locator("#recently-viewed [data-open]").count(), 4, "Recently viewed capped at four");
  equals(await page.locator("#recently-viewed [data-open]").evaluateAll((buttons) => buttons.map((button) => button.dataset.open)), ["maldives", "amalfi", "kyoto", "cancun"], "History ordered by actual view recency");
  check((await page.locator("#recommendation-note").textContent()).includes("Asia"), "Recommendations respond to last region");
  await page.reload({ waitUntil: "networkidle" });
  equals(await page.locator("#recently-viewed [data-open]").count(), 4, "History persists across reload");
  await openCard("santorini");
  equals(await page.locator("#detail-total").textContent(), "$1,798", "Default two-traveler total");
  await page.locator("#detail-travelers").selectOption("3");
  equals(await page.locator("#detail-total").textContent(), "$2,697", "Guest changes recalculate price");
  await page.locator("#review-booking").click();
  check((await page.locator("#booking-feedback").textContent()).includes("No reservation, payment or email"), "Booking review clearly does not place order");
  const dialog = page.locator("#deal-dialog");
  await dialog.locator("[data-close]").focus();
  await page.keyboard.press("Shift+Tab");
  check(await page.evaluate(() => document.activeElement.matches("#deal-dialog .detail-save")), "Backward dialog focus wraps");
  await page.keyboard.press("Tab");
  check(await page.evaluate(() => document.activeElement.matches("#deal-dialog [data-close]")), "Forward dialog focus wraps");
  await page.keyboard.press("Escape");
  check(await dialog.isHidden(), "Escape closes native dialog");
  await page.locator("#clear-history").click();
  check(await page.locator(".history-empty").isVisible(), "History clears to honest empty state");
  await page.locator('#alert-form input[name="destination"]').fill("  ");
  await page.locator('#alert-form input[name="price"]').fill("700");
  await page.locator('#alert-form input[name="email"]').fill("demo@example.com");
  await page.locator("#alert-form button").click();
  check(await page.locator('#alert-form input[name="destination"]').evaluate((input) => !input.validity.valid), "Whitespace destination rejected");
  await page.locator('#alert-form input[name="destination"]').fill("Kyoto");
  await page.locator('#alert-form input[name="price"]').fill("0");
  await page.locator("#alert-form button").click();
  check(await page.locator('#alert-form input[name="price"]').evaluate((input) => !input.validity.valid), "Non-positive price rejected");
  await page.locator('#alert-form input[name="price"]').fill("700");
  await page.locator('#alert-form input[name="email"]').fill("invalid");
  await page.locator("#alert-form button").click();
  check(await page.locator('#alert-form input[name="email"]').evaluate((input) => !input.validity.valid), "Invalid email rejected");
  await page.locator('#alert-form input[name="email"]').fill("demo@example.com");
  await page.locator("#alert-form button").click();
  check((await page.locator("#alert-feedback").textContent()).includes("No alert was created"), "Valid alert produces honest demo response");
  equals(await page.locator('#alert-form input[name="email"]').inputValue(), "", "Email cleared after demo validation");
  await page.locator("#newsletter-email").fill("not-an-email");
  await page.locator("#newsletter-form button").click();
  equals(await page.locator("#newsletter-feedback").textContent(), "", "Newsletter rejects invalid email");
  await page.locator("#newsletter-email").fill("newsletter@example.com");
  await page.locator("#newsletter-form button").click();
  check((await page.locator("#newsletter-feedback").textContent()).includes("No subscription was created"), "Newsletter signup is explicitly a demo");
  check(await page.evaluate(() => !JSON.stringify(localStorage).includes("@")), "No email address persisted");
  await page.locator('.site-footer [data-info="privacy"]').click();
  await page.locator("#clear-local-data").click();
  check((await page.locator("#privacy-feedback").textContent()).includes("expiry is unchanged"), "Local-data clearing preserves campaign expiry");
  await page.keyboard.press("Escape");
  if (width <= 1000) {
    await page.locator("#menu-toggle").click();
    check(await page.locator("#mobile-menu").isVisible(), "Responsive menu opens");
    await page.locator('#mobile-menu [data-type="Cruises"]').click();
    check(await page.locator("#mobile-menu").isHidden(), "Mobile navigation closes after selection");
    equals(await ids(), ["cruise"], "Mobile menu applies actual deal filter");
    await reset();
  }
  if (width <= 720) {
    await page.locator("#mobile-filter").click();
    equals(await page.locator("#filter-toggle").getAttribute("aria-expanded"), "true", "Bottom filter button expands accordion");
    check(await page.locator("#filter-type").isVisible(), "Mobile filter controls are accessible");
    await page.locator("#filter-toggle").click();
    check(await page.locator("#filter-fields").isHidden(), "Mobile accordion collapses");
  }
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "No page-level horizontal overflow");
  check(await page.evaluate(() => [...document.querySelectorAll("button,a,input,select")].filter((element) => element.getClientRects().length).every((element) => {
    const box = element.getBoundingClientRect();
    return box.width > 0;
  })), "Interactive controls have rendered dimensions");
  const before = await page.locator("#master-countdown").textContent();
  await page.clock.runFor(1100);
  check(await page.locator("#master-countdown").textContent() !== before, "Countdown really ticks");
  await page.clock.fastForward(12 * 3600000);
  equals(await page.locator("#flash-track .button:disabled").count(), 4, "All flash offers expire without negative time");
  equals(await page.locator("#master-countdown").textContent(), "All ended", "Master countdown handles all expired");
  await page.clock.setSystemTime(new Date());
  await page.evaluate(() => localStorage.removeItem("farefinder-campaign"));
  const fallbackContext = await page.context().browser().newContext({ viewport: page.viewportSize(), reducedMotion: "reduce" });
  const fallback = await fallbackContext.newPage();
  const fallbackErrors = [];
  fallback.on("pageerror", (error) => fallbackErrors.push(error.message));
  fallback.on("requestfailed", (request) => fallbackErrors.push(request.url()));
  fallback.on("response", (response) => { if (response.status() >= 400) fallbackErrors.push(response.url()); });
  await fallback.addInitScript(() => {
    Object.defineProperty(window, "localStorage", { get() { throw new DOMException("Blocked", "SecurityError"); } });
  });
  await fallback.goto(page.url(), { waitUntil: "networkidle" });
  await fallback.locator('#deals-grid [data-save="santorini"]').click();
  equals(await fallback.locator("#saved-count").textContent(), "1", "Saved deals work in memory when storage denied");
  await fallback.locator('#deals-grid [data-deal="santorini"] .button[data-open]').click();
  equals(await fallback.locator("#recently-viewed [data-open]").count(), 1, "History works when storage denied");
  check((await fallback.locator("#toast").textContent()).includes("Storage unavailable"), "Storage fallback is disclosed");
  equals(fallbackErrors, [], "Storage-denied page has no runtime or resource errors");
  await fallbackContext.close();
  if (width === 1440) {
    const motion = await page.context().browser().newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: "no-preference" });
    await motion.clock.install();
    await motion.goto(page.url(), { waitUntil: "networkidle" });
    equals(await motion.locator("#flash-play").getAttribute("aria-pressed"), "true", "Desktop carousel starts automatically without reduced motion");
    await motion.locator("#flash-track").scrollIntoViewIfNeeded();
    await motion.mouse.move(0, 0);
    await motion.clock.runFor(6100);
    await motion.waitForFunction(() => document.querySelector("#flash-track").scrollLeft > 0);
    check(await motion.locator("#flash-track").evaluate((element) => element.scrollLeft > 0), "Desktop autoplay actually advances carousel");
    await motion.locator("#flash-play").click();
    equals(await motion.locator("#flash-play").getAttribute("aria-pressed"), "false", "Desktop autoplay has a working pause control");
    await motion.close();
  }
  return scenarios;
}
