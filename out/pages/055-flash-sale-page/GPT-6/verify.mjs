export async function verify(page,nodeAssert){
  let checks=0;const assert=(condition,message)=>{nodeAssert.ok(condition,message);checks++;};
  await page.clock.install({time:new Date('2026-11-13T10:00:00Z')});
  await page.setViewportSize({width:1440,height:1000});await page.goto(page.url());
  const grid=page.locator('#deals-grid');
  assert(await grid.locator('.product-card').count()===9,'Nine additional sample deal cards');
  assert((await page.locator('#featured-saving').innerText()).includes('$160.00 (45.7%'),'Featured saving correctly calculates cents and percentage');
  assert(await page.locator('#max-discount').innerText()==='46.2%','Maximum actual reduction includes extra lightning discount');
  await page.locator('#search').fill('Bose');
  assert(await grid.locator('.product-card').count()===1,'Product search filters actual catalog');
  await page.locator('#search').fill('<img src=x>');
  assert(await grid.locator('.product-card').count()===0&&await page.locator('#results img').count()===0,'User query is safe text and honest empty state');
  await page.locator('#reset').click();
  await page.locator('[data-category="Smartphones"]').click();
  assert(await page.locator('#empty').isVisible(),'Unimplemented smartphone category has no fake deals');
  await page.locator('#reset').click();
  await page.locator('#sort').selectOption('price-low');
  assert(await grid.locator('.product-card').first().getAttribute('data-product')==='logitech','Sorting prices uses numeric cents');
  await grid.locator('[data-save="macbook"]').click();await page.locator('#wishlist-filter').click();
  assert(await grid.locator('.product-card').count()===1&&await page.locator('#saved-count').innerText()==='1','Wishlist filters actual saved products');
  await grid.locator('[data-save="macbook"]').click();
  assert(await page.locator('#empty').isVisible(),'Unsaving last wishlist item updates empty view');
  await page.locator('#reset').click();
  await grid.locator('[data-detail="gopro"]').first().click();
  assert(await page.locator('#detail-dialog').isVisible(),'Product details open real local information');
  await page.keyboard.press('Escape');
  assert((await page.locator('#recent-label').innerText()).includes('Viewed during this page session')&&await page.locator('#recent-grid .recent-card').count()===1,'Recently viewed uses actual current-session browsing');
  const tv=grid.locator('[data-add="samsung"]');
  for(let i=0;i<3;i++)await tv.click();
  assert(await tv.isDisabled(),'Cannot oversell three-unit simulated inventory');
  await page.locator('#open-cart').click();
  assert(await page.locator('#cart-subtotal').innerText()==='$4,197.00','Cart multiplies quantities accurately');
  await page.locator('[data-quantity="samsung"][data-delta="-1"]').click();
  assert(await page.locator('#cart-subtotal').innerText()==='$2,798.00','Decreasing quantity restores sample stock and totals');
  await page.locator('[data-remove="samsung"]').click();
  assert(await page.locator('#checkout').isDisabled(),'Empty cart cannot preview checkout');
  await page.keyboard.press('Escape');
  assert(!await tv.isDisabled(),'Removing item restores simulated availability');
  await grid.locator('[data-add="airpods"]').click();
  await page.locator('#lightning-track [data-add="airpods"]').click();
  await page.locator('#open-cart').click();
  assert(await page.locator('#cart-subtotal').innerText()==='$304.20','Extra ten-percent saving applies lower price to both cart units');
  await page.locator('[data-quantity="airpods"][data-delta="1"]').click();
  assert(await page.locator('#cart-subtotal').innerText()==='$456.30','Increasing lightning quantity retains discounted price');
  await page.locator('[data-remove="airpods"]').click();await page.keyboard.press('Escape');
  await page.locator('.featured-details [data-add="sony"]').click();
  await page.locator('#lightning-track [data-add="kindle"]').click();
  await page.locator('#open-cart').click();
  assert(await page.locator('#cart-total').innerText()==='$274.59','Mixed cent prices and free demo shipping total exactly');
  await page.locator('#checkout').click();
  assert((await page.locator('#checkout-status').innerText()).includes('No payment collected'),'Checkout is clearly a local preview');
  await page.clock.fastForward(1100);
  assert((await page.locator('#checkout-status').innerText()).includes('No payment collected'),'Countdown tick preserves checkout preview feedback');
  await page.keyboard.press('Escape');
  await page.locator('#lightning-next').click();
  await page.waitForFunction(()=>document.querySelector('#lightning-track').scrollLeft>0);
  assert(await page.locator('#lightning-track').evaluate(track=>track.scrollLeft>0),'Carousel arrow actually scrolls');
  await page.locator('#email').fill('demo@example.com');await page.locator('#alert-form button').click();
  assert((await page.locator('#email-status').innerText()).includes('No subscription created'),'Email alert is a safe local preview');
  await page.clock.fastForward(24*3600000);
  assert(await page.locator('.featured-details [data-add="sony"]').isDisabled(),'Expired offer cannot be added');
  assert(await page.locator('#hours').innerText()==='00'&&await page.locator('#minutes').innerText()==='00'&&await page.locator('#seconds').innerText()==='00','Master clock clamps at zero');
  await page.locator('#open-cart').click();
  assert(await page.locator('#checkout').isDisabled()&&(await page.locator('#checkout-status').innerText()).includes('expired'),'Expired cart offers block checkout preview');
  await page.clock.fastForward(60000);
  assert(await page.locator('#hours').innerText()==='00','Expired countdown never loops');
  await page.keyboard.press('Escape');await page.reload();
  assert(await page.locator('#cart-count').innerText()==='0'&&await page.locator('#saved-count').innerText()==='0','Refresh resets memory-only cart and wishlist');
  await page.setViewportSize({width:390,height:900});
  await page.locator('#mobile-search').fill('Kindle');
  assert(await grid.locator('.product-card').count()===1,'Mobile search remains usable');
  await page.locator('#mobile-search').fill('');
  await page.locator('#menu').click();
  assert(await page.locator('#nav').isVisible(),'Mobile navigation opens');
  await page.locator('#nav a[href="#deals"]').first().click();
  assert(await page.locator('#menu').getAttribute('aria-expanded')==='false','Mobile anchor closes navigation');
  await page.locator('.featured-details [data-add="sony"]').click();
  assert(await page.locator('#cart-sticky').isVisible()&&await page.locator('#sticky-count').innerText()==='1','Mobile sticky cart uses actual cart count');
  await page.locator('#sticky-cart').click();
  assert(await page.locator('#cart-dialog').isVisible(),'Sticky cart opens actual local basket');
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:320,height:900});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Sticky cart and product layout fit 320px');
  await page.reload();
  return checks;
}
