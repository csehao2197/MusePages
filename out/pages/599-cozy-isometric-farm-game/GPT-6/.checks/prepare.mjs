import path from "node:path";
import { fileURLToPath } from "node:url";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as Lucide from "lucide-react";
import { WorkspaceFiles, StaticHomepage } from "../../../../../src/workflows/script/render-prompt-page.mjs";

const root = process.cwd();
const folder = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const job = JSON.parse(await readFile(path.join(root, "src", "workflows", "script", ".ai-gpt6-current-job.json"), "utf8"));
if (job.prompt !== "599-cozy-isometric-farm-game" || job.output !== folder || job.modelId !== "gpt-6.1-sol") throw Error("Job mismatch");
const manifest = JSON.parse(await readFile(job.stateFile, "utf8"));
const pid = Number((await readFile(job.promptLock, "utf8")).trim());
if (pid !== manifest.ownedLock.pid || manifest.ownedLock.prompt !== job.prompt || manifest.runId !== job.runId) throw Error("Lock identity mismatch");
process.kill(pid, 0);
const metadataFile = path.join(folder, "metadata.json");
let metadata;
try
{
    metadata = JSON.parse(await readFile(metadataFile, "utf8"));
}
catch (error)
{
    if (error.code !== "ENOENT") throw error;
}
if (!metadata)
{
    metadata = { modelId: job.modelId, tags: ["Farming", "Isometric", "Cozy"], staticDir: "out", generated: false, preview: false, validated: false, config_added: false };
    await WorkspaceFiles.saveJson(metadataFile, metadata);
}
const exported = await WorkspaceFiles.ensureDirectory(root, path.relative(root, folder), "out");
await mkdir(path.join(folder, "fonts"), { recursive: true });
await mkdir(path.join(folder, "licenses"), { recursive: true });
for (const weight of [600, 700])
{
    await copyFile(path.join(root, "out", "pages", "554-flower-anatomy-3d-explainer", "GPT-6", "node_modules", "@fontsource", "fraunces", "files", `fraunces-latin-${weight}-normal.woff2`), path.join(folder, "fonts", `fraunces-${weight}.woff2`));
}
await copyFile(path.join(root, "out", "pages", "549-preschool-website", "GPT-6", "public", "fonts", "nunito-sans-latin-wght-normal.woff2"), path.join(folder, "fonts", "nunito-sans.woff2"));
await copyFile(path.join(root, "out", "pages", "549-preschool-website", "GPT-6", "public", "fonts", "NUNITO-LICENSE.txt"), path.join(folder, "licenses", "NUNITO.txt"));
await copyFile(path.join(root, "out", "pages", "554-flower-anatomy-3d-explainer", "GPT-6", "node_modules", "@fontsource", "fraunces", "LICENSE"), path.join(folder, "licenses", "FRAUNCES.txt"));
await copyFile(path.join(root, "node_modules", "lucide-react", "LICENSE"), path.join(folder, "licenses", "LUCIDE.txt"));
const names = ["Sprout", "Shovel", "Droplets", "Hand", "Sunset", "Sun", "Check", "HelpCircle", "RotateCcw", "X", "Coins", "ShoppingBasket"];
await writeFile(path.join(folder, "icons.js"), `export const icons = ${JSON.stringify(Object.fromEntries(names.map((name) => [name, renderToStaticMarkup(createElement(Lucide[name]))])), null, 4)};\n`);
await copyFile(path.join(folder, "src", "content.ts"), path.join(folder, "content.js"));
for (const name of ["engine", "storage"])
{
    await writeFile(path.join(folder, `${name}.js`), (await readFile(path.join(folder, "src", "game", `${name}.js`), "utf8")).replaceAll('"../content.js"', '"./content.js"'));
}
await WorkspaceFiles.saveText(path.join(folder, "LICENSE"), `${await readFile(path.join(root, job.provenance.license_file), "utf8")}\nPrompt by VibeFather. Original source: ${job.provenance.source_url}\nOriginal game SVG/CSS and static adaptation generated by gpt-6.1-sol (public label GPT-6).\n`);
for (const name of ["index.html", "styles.css", "app.js", "content.js", "engine.js", "storage.js", "icons.js", "favicon.svg", "LICENSE"])
{
    await copyFile(path.join(folder, name), path.join(exported, name));
}
for (const directory of ["fonts", "licenses"])
{
    await mkdir(path.join(exported, directory), { recursive: true });
    const { readdir } = await import("node:fs/promises");
    for (const name of await readdir(path.join(folder, directory)))
    {
        await copyFile(path.join(folder, directory, name), path.join(exported, directory, name));
    }
}
const fingerprint = createHash("sha256").update(JSON.stringify([await readFile(job.file, "utf8"), await readFile(path.join(root, "src", "workflows", "AI Agent", "DESIGN.md"), "utf8")])).digest("hex");
await WorkspaceFiles.saveText(path.join(folder, ".generation-input.sha256"), fingerprint + "\n");
await StaticHomepage.checkSource(folder);
metadata.generated = true;
await WorkspaceFiles.saveJson(metadataFile, metadata);
const digest = await StaticHomepage.validateStaticOutput(exported, "cozy-isometric-farm-game", "GPT-6");
console.log(JSON.stringify({ sourceChecked: true, digest, exported }));
